"""Bind retained main-task and audit counterexamples to public Racket receipts."""
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path

p = argparse.ArgumentParser(description=__doc__)
p.add_argument('checks', type=Path)
a = p.parse_args()
checks = a.checks.resolve()
read = lambda path: json.loads(path.read_text())


def valid(report, task, count):
    assert report['task_id'] == task and report['rule_hash_matches_catalog']
    assert len(report['results']) == count
    assert all(row['error'] is None and row['valid_output'] for row in report['results'])


def save(path, report, facts):
    row = {'status': 'pass', 'task_id': report['task_id'],
           'generator_sha256': report['generator_sha256'],
           'executed_rule_hash': report['executed_rule_hash'], **facts}
    path.write_text(json.dumps(row, indent=2) + '\n')
    print(json.dumps(row))


main = read(checks / 'main-reference-racket.json')
expected = read(checks / 'main-reference-expected.json')
valid(main, '2006f915df8b', 10)
for got, want in zip(main['results'], expected):
    assert got['input'] == want['input'] and got['output'] == want['expected']
save(checks / 'main-reference-validation.json', main, {
    'reference_report': 'checks/main-reference-racket.json', 'canonical_pairs_matched': 5,
    'intermediate_counterexample_pairs_matched': 5,
    'intermediate_input_generator_sha256': expected[0]['input_generator_sha256'],
    'note': 'Current Racket authority applied to retained intermediate inputs; those inputs were not regenerated by the current sampler.'})

home = checks / 'audit/5ec933db2c3a'
