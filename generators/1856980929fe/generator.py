"""Canonical-scale input sampler for the green-rectangle V-fan task.

The unchanged Racket authority finds every solid green rectangle and repeats
that rectangle downward in rh-row bands.  At band k it stamps one copy k*rw
columns left and one k*rw columns right, clipping at the canvas boundary.
Outputs are generated by the authority, not by this module; ``rule_mirror`` is
an independent executable oracle used only by focused tests and semantic gates.
"""
