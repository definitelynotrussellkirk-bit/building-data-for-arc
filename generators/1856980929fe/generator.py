def schedule_profile(seed, sample_index, difficulty=None):
    """Return the deterministic placement schedule used by ``generate``."""
    band_offset = {"easy": 0, "medium": 1, "hard": 2}.get(difficulty, 3)
    index = (int(seed) + int(sample_index) + band_offset) % len(SCHEDULE_PROFILES)
    return SCHEDULE_PROFILES[index]


def _validate_overrides(overrides):
    unknown = set(overrides) - set(AXES)
    if unknown:
        raise ValueError(f"unknown override axes: {sorted(unknown)}")
    for name in ("grid_h", "grid_w", "n_seeds"):
        if name in overrides and overrides[name] is not None and type(overrides[name]) is not int:
            raise ValueError(f"{name} must be an integer, not {type(overrides[name]).__name__}")
    if "rect_size" in overrides and overrides["rect_size"] is not None:
        if type(overrides["rect_size"]) is not str:
            raise ValueError("rect_size must be a string")
        if overrides["rect_size"] not in RECT_SIZE_NAMES:
            raise ValueError(f"rect_size must be one of {RECT_SIZE_NAMES}")


def _seed_sizes(ctx, n_seeds, forced_size):
    first = ctx.draw_choice("rect_size", RECT_SIZE_NAMES)
    if forced_size is not None:
        return [tuple(int(v) for v in forced_size.split("x"))] * n_seeds

    names = [first]
    for index in range(1, n_seeds):
        # A multi-seed lesson always contains parameter diversity.  This is a
        # semantic witness, not cosmetic randomness: it rules out applying the
        # first seed's dimensions globally to all seeds.
        used = set(names)
        options = [name for name in RECT_SIZE_NAMES if name not in used]
        if not options:
            options = list(RECT_SIZE_NAMES)
        names.append(ctx.draw_rng(f"rect_size_{index}").choice(options))
    return [tuple(int(v) for v in name.split("x")) for name in names]


def _has_visible_first_level(h, w, box):
    r, c, rh, rw = box
    vertical = r + 2 * rh <= h
    left_full = c - rw >= 0
    right_full = c + 2 * rw <= w
    return vertical and (left_full or right_full)


def _separated(box, others):
    """Keep components distinct even under 8-neighbour inspection."""
    r, c, rh, rw = box
    for rr, cc, rrh, rrw in others:
        # Half-open rectangles expanded by one cell touch iff both expanded
        # projections overlap.  Reject that; a blank moat remains.
        rows_near = r <= rr + rrh and rr <= r + rh
        cols_near = c <= cc + rrw and cc <= c + rw
        if rows_near and cols_near:
            return False
    return True


def _placement_candidates(h, w, size, profile, *, first):
    rh, rw = size
    max_r = h - 2 * rh
    max_c = w - rw
    if max_r < 0 or max_c < 0:
        return []
    candidates = []
    for r in range(max_r + 1):
        for c in range(max_c + 1):
            box = (r, c, rh, rw)
            if not _has_visible_first_level(h, w, box):
                continue
            if first:
                if profile == "upper" and r > h // 3:
                    continue
                if profile == "lower" and r < h // 2:
                    continue
                if profile == "left_edge" and not c < rw:
                    continue
                if profile == "right_edge" and not c + 2 * rw > w:
                    continue
            candidates.append(box)
    return candidates


def _place_rectangles(ctx, h, w, sizes, profile):
    candidate_lists = []
    for index, size in enumerate(sizes):
        candidates = _placement_candidates(h, w, size, profile, first=index == 0)
        ctx.draw_rng(f"placement_{index}").shuffle(candidates)
        candidate_lists.append(candidates)

    placed = []

    def search(index):
        if index == len(candidate_lists):
            return True
        for box in candidate_lists[index]:
            if not _separated(box, placed):
                continue
            placed.append(box)
            if search(index + 1):
                return True
            placed.pop()
        return False

    if not search(0):
        raise ValueError(
            f"could not place {len(sizes)} separated rectangles on {h}x{w} "
            f"under profile {profile!r}"
        )
    return placed


def generate(seed, sample_index, *, difficulty=None, **overrides):
    _validate_overrides(overrides)
    ctx = gen_ctx(
        seed=seed,
        sample_index=sample_index,
        version=VERSION,
        task_id=TASK_ID,
        difficulty=difficulty,
        overrides=overrides,
    )
    h = ctx.draw_int("grid_h", 25, 29)
    w = ctx.draw_int("grid_w", 22, 29)
    # All exact values remain available in every band.  Repetition merely
    # makes multi-seed, parameter-diverse lessons common enough to teach the
    # independent-per-seed rule reliably.
    n_seeds = ctx.draw_choice("n_seeds", (1, 2, 2, 2, 3, 3, 3))
    forced_size = overrides.get("rect_size")
    sizes = _seed_sizes(ctx, n_seeds, forced_size)
    profile = schedule_profile(seed, sample_index, difficulty)
    boxes = _place_rectangles(ctx, h, w, sizes, profile)

    grid = full_grid(h, w, 0)
    for r, c, rh, rw in boxes:
        for rr in range(r, r + rh):
            for cc in range(c, c + rw):
                grid[rr][cc] = 3
    return grid


def _rectangles(grid):
    """Return 4-connected green component bounding boxes, sorted top-left."""
    if not isinstance(grid, (list, tuple)) or not grid:
        return []
    if not isinstance(grid[0], (list, tuple)) or not grid[0]:
        return []
    h, w = len(grid), len(grid[0])
    if any(not isinstance(row, (list, tuple)) or len(row) != w for row in grid):
        return []

    seen = set()
    rectangles = []
    for r in range(h):
        for c in range(w):
            if grid[r][c] != 3 or (r, c) in seen:
                continue
            queue = deque([(r, c)])
            seen.add((r, c))
            points = []
            while queue:
                rr, cc = queue.popleft()
                points.append((rr, cc))
                for dr, dc in ((-1, 0), (1, 0), (0, -1), (0, 1)):
                    nr, nc = rr + dr, cc + dc
                    if (
                        0 <= nr < h
                        and 0 <= nc < w
                        and grid[nr][nc] == 3
                        and (nr, nc) not in seen
                    ):
                        seen.add((nr, nc))
                        queue.append((nr, nc))
            rows = [point[0] for point in points]
            cols = [point[1] for point in points]
            r0, c0 = min(rows), min(cols)
            rh, rw = max(rows) - r0 + 1, max(cols) - c0 + 1
            rectangles.append((r0, c0, rh, rw))
    return sorted(rectangles)


def _corner_rectangles(grid):
    """Mirror the Racket authority's corner/run-length extraction exactly."""
    h, w = len(grid), len(grid[0])
    rectangles = []
    for r in range(h):
        for c in range(w):
            if grid[r][c] != 3:
                continue
            if r > 0 and grid[r - 1][c] == 3:
                continue
            if c > 0 and grid[r][c - 1] == 3:
                continue
            rh = 1
            while r + rh < h and grid[r + rh][c] == 3:
                rh += 1
            rw = 1
            while c + rw < w and grid[r][c + rw] == 3:
                rw += 1
            rectangles.append((r, c, rh, rw))
    return rectangles


def _fan_output(grid, rectangles, *, max_level=None):
    h, w = len(grid), len(grid[0])
    out = full_grid(h, w, 0)
    for r, row in enumerate(grid):
        for c, value in enumerate(row):
            if value == 3:
                out[r][c] = 3
    for r0, c0, rh, rw in rectangles:
        level = 1
        while r0 + level * rh < h and (max_level is None or level <= max_level):
            row_start = r0 + level * rh
            for rr in range(row_start, min(row_start + rh, h)):
                for col_start in (c0 - level * rw, c0 + level * rw):
                    for cc in range(max(0, col_start), min(w, col_start + rw)):
                        out[rr][cc] = 3
            level += 1
    return out


def rule_mirror(grid):
    """Independent Python mirror of the pinned Racket rule; never mutates input."""
    if not isinstance(grid, (list, tuple)) or not grid:
        raise ValueError("expected a nonempty grid")
    if not isinstance(grid[0], (list, tuple)) or not grid[0]:
        raise ValueError("expected a nonempty grid")
    width = len(grid[0])
    if any(not isinstance(row, (list, tuple)) or len(row) != width for row in grid):
        raise ValueError("expected a rectangular grid")
    return _fan_output(grid, _corner_rectangles(grid))


def observe_overrides(grid):
    """Recover every exact integer axis from returned pixels."""
    rectangles = _rectangles(grid)
    return {
        "grid_h": len(grid),
        "grid_w": len(grid[0]),
        "n_seeds": len(rectangles),
    }


def self_check(grid, *, difficulty=None, meta=None):
    if not isinstance(grid, (list, tuple)) or not grid:
        return ["expected a nonempty rectangular grid"]
    if not isinstance(grid[0], (list, tuple)) or not grid[0]:
        return ["expected a nonempty rectangular grid"]
    h, w = len(grid), len(grid[0])
    if any(not isinstance(row, (list, tuple)) or len(row) != w for row in grid):
        return ["grid must be rectangular"]

    errors = []
    if not 25 <= h <= 29:
        errors.append(f"grid height {h} outside canonical range 25..29")
    if not 22 <= w <= 29:
        errors.append(f"grid width {w} outside canonical range 22..29")
    if any(type(value) is not int or value not in (0, 3) for row in grid for value in row):
        errors.append("input cells must be integer colors 0 or 3")
        return errors

    rectangles = _rectangles(grid)
    if not 1 <= len(rectangles) <= 3:
        errors.append(f"expected 1..3 separated green rectangles, found {len(rectangles)}")
    green_count = sum(value == 3 for row in grid for value in row)
    rectangle_area = sum(rh * rw for _, _, rh, rw in rectangles)
    if rectangle_area != green_count:
        errors.append("every green component must fill its rectangular bounding box")
    for index, box in enumerate(rectangles):
        _, _, rh, rw = box
        if (rh, rw) not in _CANONICAL_SIZE_SET:
            errors.append(f"rectangle {index} has noncanonical size {rh}x{rw}")
        if not _has_visible_first_level(h, w, box):
            errors.append(f"rectangle {index} has no complete visible first fan level")
    return errors


def strict_canonical_like(grid):
    """Accept exactly this generator's lawful canonical-scale input manifold."""
    return self_check(grid)


def _shared_first_size(grid):
    """RIVAL: incorrectly reuse the first seed's dimensions for every seed."""
    rectangles = _corner_rectangles(grid)
    if not rectangles:
        return [list(row) for row in grid]
    rh, rw = rectangles[0][2:]
    wrong = [(r, c, rh, rw) for r, c, _, _ in rectangles]
    return _fan_output(grid, wrong)


def _single_fan_level(grid):
    """RIVAL: stamp k=1 only and omit all deeper fan levels."""
    return _fan_output(grid, _corner_rectangles(grid), max_level=1)


def _first_two_seeds_only(grid):
    """RIVAL: expand only the first two seeds; retain later seeds unchanged."""
    return _fan_output(grid, _corner_rectangles(grid)[:2])


def _mixed_seed_size_witness(grid):
    rectangles = _rectangles(grid)
    return (
        len({(rh, rw) for _, _, rh, rw in rectangles}) > 1
        and _shared_first_size(grid) != rule_mirror(grid)
    )


def _deeper_level_witness(grid):
    return _single_fan_level(grid) != rule_mirror(grid)


def _third_seed_expansion_witness(grid):
    return (
        len(_rectangles(grid)) >= 3
        and _first_two_seeds_only(grid) != rule_mirror(grid)
    )


