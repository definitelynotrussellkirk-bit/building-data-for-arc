def lesson_identifiable(demos, query):
    """Reject a lesson iff a declared rival fits demos but changes the query."""
    reasons = []
    query_input = query["input"]
    authority_query = rule_mirror(query_input)
    for name, rival in LESSON_COMPETITORS.items():
        survives = all(rival(example["input"]) == example["output"] for example in demos)
        if survives and rival(query_input) != authority_query:
            reasons.append(f"{name} fits every demo but changes the query answer")
    return reasons
