def generate(seed, sample_index, *, difficulty=None, **overrides):
    ctx = gen_ctx(seed=seed, sample_index=sample_index,
                  version=VERSION, task_id=TASK_ID,
                  difficulty=difficulty, overrides=overrides)
    if overrides.get("texture") in DEGENERATE_TEXTURES:
        return _draw_from_degenerate(overrides["texture"], None)
    if ctx.draw_int("emit_canonical", 0, 1) == 1:
        idx = ctx.draw_int("canon_idx", 0, len(_CANON_INPUTS) - 1)
        return [row[:] for row in _CANON_INPUTS[idx]]
    if difficulty == "easy":
        size = ctx.draw_int("grid_size", 13, 13)
    elif difficulty == "hard":
        size = ctx.draw_int("grid_size", 16, 18)
    else:
        size = ctx.draw_int("grid_size", 13, 16)
    rng = ctx.draw_rng("layout")
    g = full_grid(size, size, rng.choice([1, 3, 4, 8, 9]))
    patch = [row[:] for row in rng.choice(_PATCHES)]
    side = len(patch)
    paste(g, patch, rng.randint(1, size - side - 1), rng.randint(1, size - side - 1))
    return g


def _draw_from_degenerate(name, rng):
    size = 14
    g = full_grid(size, size, 1)
    if name == "no_patch":
        # Background-only grid with no 11x11 patch — rule has no
        # texture window and no orange band to inpaint.
        return g
    if name == "no_orange":
        # Patch present but the orange band is replaced with bg —
        # rule has no damage marker, output equals input.
        for r in range(size):
            for c in range(size):
                g[r][c] = 9
        return g
    if name == "full_orange":
        # Entire grid is orange-7 — rule's local-table repair has no
        # surrounding texture to copy from.
        for r in range(size):
            for c in range(size):
                g[r][c] = 7
        return g
    return g


def self_check(grid, *, difficulty=None, meta=None):
    msgs = []
    if not grid or not grid[0] or any(len(row) != len(grid[0]) for row in grid):
        return ["grid must be a non-empty rectangle"]
    h, w = len(grid), len(grid[0])
    if h != w:
        msgs.append(f"inpaint examples should be square; got {h}x{w}")
    if h not in {13, 14, 15, 16, 17, 18, 30}:
        msgs.append(f"unexpected inpaint grid side length {h}")
    vals = [v for row in grid for v in row]
    orange = sum(1 for v in vals if v == 7)
    if orange < 8:
        msgs.append("expected a visible orange-7 damage band")
    if len({v for v in vals if v != 7}) < 3:
        msgs.append("expected a non-orange texture palette around the damaged band")
    if orange == len(vals):
        msgs.append("full-orange grid is a degenerate texture, not a default example")
    return msgs
