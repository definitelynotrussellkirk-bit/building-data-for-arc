#!/usr/bin/env python3
"""Isolated episode-level arm-turn parameter for task 0d1deab2505c.

The selected production generator and canonical Racket authority stay unchanged.
This prototype varies one nearby rule parameter once per episode:

* ``half_turn`` (canonical/default): opposite arm colors swap around the moved center.
* ``preserve``: the creature moves identically, but arm colors keep orientation.

All object detection, tail transport, wall destination, background, and color roles
remain unchanged.  Racket execution supplies the retained evidence labels.
"""
from __future__ import annotations

import argparse
import copy
import hashlib
import importlib.util
import json
from pathlib import Path
from typing import Any

TASK_ID = "0d1deab2505c"
PROTOTYPE_VERSION = "1.0.0"
ALLOWED_ARM_TURNS = ("half_turn", "preserve")
DEFAULT_ARM_TURN = "half_turn"


def _validate_arm_turn(arm_turn: str) -> str:
    if arm_turn not in ALLOWED_ARM_TURNS:
        raise ValueError(
            f"arm_turn must be one of {ALLOWED_ARM_TURNS}, got {arm_turn!r}"
        )
    return arm_turn


def _validate_seed(seed: int) -> int:
    if type(seed) is not int:
        raise TypeError("seed must be an integer (not bool)")
    return seed


def choose_arm_turn(seed: int) -> str:
    """Choose one hidden setting deterministically for an entire episode."""
    _validate_seed(seed)
    digest = hashlib.sha256(f"{TASK_ID}|arm_turn|{seed}".encode()).digest()
    return ALLOWED_ARM_TURNS[digest[0] % len(ALLOWED_ARM_TURNS)]


def _generator_path() -> Path:
    return Path(__file__).resolve().parents[2] / "generator.py"


def _load_generator():
    source = _generator_path()
    spec = importlib.util.spec_from_file_location("parametric_0d1deab2505c_generator", source)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"cannot import selected generator from {source}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def apply_python(grid: list[list[int]], arm_turn: str) -> list[list[int]]:
    """Diagnostic Python mirror; retained labels are generated by Racket."""
    setting = _validate_arm_turn(arm_turn)
    generator = _load_generator()
    creatures = generator.parse_creatures(grid)
    out = copy.deepcopy(grid)

    for creature in creatures:
        for row, col in set(creature["body"]) | set(creature["tail"]):
            out[row][col] = 8

    for creature in creatures:
        center_row, center_col = creature["center"]
        shift_row, shift_col = creature["shift"]
        moved_row = center_row + shift_row
        moved_col = center_col + shift_col

        for row, col in creature["tail"]:
            out[row + shift_row][col + shift_col] = 1
        out[moved_row][moved_col] = 4

        for arm_row, arm_col in generator._ARM_DELTAS:
            if setting == "half_turn":
                source_row = center_row - arm_row
                source_col = center_col - arm_col
            else:
                source_row = center_row + arm_row
                source_col = center_col + arm_col
            out[moved_row + arm_row][moved_col + arm_col] = grid[source_row][source_col]
    return out


def program_for(arm_turn: str) -> str:
    """Materialize the exact Racket rule for one bounded parameter setting."""
    setting = _validate_arm_turn(arm_turn)
    if setting == "half_turn":
        top, bottom, left, right = (
            "(cell-down g cr cc)",
            "(cell-up g cr cc)",
            "(cell-right g cr cc)",
            "(cell-left g cr cc)",
        )
    else:
        top, bottom, left, right = (
            "(cell-up g cr cc)",
            "(cell-down g cr cc)",
            "(cell-left g cr cc)",
            "(cell-right g cr cc)",
        )
    return f"""(rule!
 (lambda (g)
   (let ()
     (define bg 8)
     (define (creature center)
       (let* ((cr (first center)) (cc (second center))
              (dir (cond ((and (in-bounds? (- cr 2) cc h w)
                               (= (at g (- cr 2) cc) 1)) 'up)
                         ((and (in-bounds? (+ cr 2) cc h w)
                               (= (at g (+ cr 2) cc) 1)) 'down)
                         ((and (in-bounds? cr (- cc 2) h w)
                               (= (at g cr (- cc 2)) 1)) 'left)
                         ((and (in-bounds? cr (+ cc 2) h w)
                               (= (at g cr (+ cc 2)) 1)) 'right)
                         (else 'none)))
              (seed (cond ((eq? dir 'up) (list (- cr 2) cc))
                          ((eq? dir 'down) (list (+ cr 2) cc))
                          ((eq? dir 'left) (list cr (- cc 2)))
                          ((eq? dir 'right) (list cr (+ cc 2)))
                          (else (list cr cc))))
              (tail (connected-region g (first seed) (second seed)
                                      (lambda (r c v) (= v 1)) 8))
              (body (list (list cr cc) (list (- cr 1) cc)
                          (list (+ cr 1) cc) (list cr (- cc 1))
                          (list cr (+ cc 1))))
              (bb (bbox-of-cells (append body tail)))
              (dr (cond ((eq? dir 'down) (- 0 (first bb)))
                        ((eq? dir 'up) (- (- h 1) (third bb)))
                        (else 0)))
              (dc (cond ((eq? dir 'right) (- 0 (second bb)))
                        ((eq? dir 'left) (- (- w 1) (fourth bb)))
                        (else 0))))
         (list (append body tail)
               (list (list (+ cr dr) (+ cc dc) 4)
                     (list (+ cr dr -1) (+ cc dc) {top})
                     (list (+ cr dr 1) (+ cc dc) {bottom})
                     (list (+ cr dr) (+ cc dc -1) {left})
                     (list (+ cr dr) (+ cc dc 1) {right}))
               (map (lambda (p) (list (+ (first p) dr)
                                      (+ (second p) dc)))
                    tail))))
     (define creatures
       (map creature
            (filter (lambda (p) (= (at g (first p) (second p)) 4))
                    (grid-positions g))))
     (for/fold ((out (erase-cells g (flatmap first creatures) bg)))
               ((c (in-list creatures)))
       (paint-cells (paint-cells out (third c) 1) (second c))))))"""


def program_sha256(arm_turn: str) -> str:
    return hashlib.sha256(program_for(arm_turn).encode()).hexdigest()


def _rule_body(program: str) -> str:
    text = program.strip()
    if not text.startswith("(rule!") or not text.endswith(")"):
        raise ValueError("prototype program must be a (rule! BODY) form")
    return text[len("(rule!") : -1].strip()


def _grid_literal(grid: list[list[int]]) -> str:
    rows = " ".join("(" + " ".join(map(str, row)) + ")" for row in grid)
    return f"'({rows})"


def apply_racket(bridge, program: str, grid: list[list[int]]) -> list[list[int]]:
    """Execute the exact materialized rule body in the protected Racket prelude."""
    body = _rule_body(program)
    expression = (
        f"(let* ((g {_grid_literal(grid)}) (h (rows g)) (w (cols g))) "
        f"({body} g))"
    )
    result = bridge.eval_text(expression)
    if not isinstance(result, list):
        raise RuntimeError(f"Racket returned a non-grid result: {result!r}")
    return result


def _episode_inputs(seed: int) -> list[list[list[int]]]:
    generator = _load_generator()
    # One complete three-phase teaching cycle plus a fresh canonical-family query.
    return [
        generator.generate(seed, sample_index, difficulty="medium")
        for sample_index in (0, 1, 2, 3)
    ]


def build_episode(seed: int, arm_turn: str | None = None) -> dict[str, Any]:
    """Build three demonstrations and one query for one fixed hidden setting."""
    _validate_seed(seed)
    setting = choose_arm_turn(seed) if arm_turn is None else _validate_arm_turn(arm_turn)
    pairs = [
        {"input": copy.deepcopy(grid), "output": apply_python(grid, setting)}
        for grid in _episode_inputs(seed)
    ]
    return {
        "schema": "arcpuzzles-parametric-arm-turn-episode-v1",
        "train": pairs[:3],
        "test": pairs[3:],
        "program": program_for(setting),
        "meta": {
            "task_id": TASK_ID,
            "seed": seed,
            "arm_turn": setting,
            "canonical_default": DEFAULT_ARM_TURN,
            "prototype_version": PROTOTYPE_VERSION,
            "sample_indices": [0, 1, 2, 3],
        },
    }


def public_challenge(episode: dict[str, Any]) -> dict[str, Any]:
    """Hide the episode parameter and query answer from the public view."""
    return {
        "schema": "arcpuzzles-parametric-arm-turn-public-v1",
        "train": copy.deepcopy(episode["train"]),
        "test": [{"input": copy.deepcopy(pair["input"])} for pair in episode["test"]],
    }


def parameter_rival_findings(episode: dict[str, Any]) -> list[str]:
    setting = episode["meta"]["arm_turn"]
    rival = next(value for value in ALLOWED_ARM_TURNS if value != setting)
    findings: list[str] = []
    if not any(apply_python(pair["input"], rival) != pair["output"]
               for pair in episode["train"]):
        findings.append(f"rival setting {rival!r} fits every demonstration")
    if any(apply_python(pair["input"], rival) == pair["output"]
           for pair in episode["test"]):
        findings.append(f"query does not distinguish rival setting {rival!r}")
    return findings


def _sha256_json(value: Any) -> str:
    payload = json.dumps(value, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(payload.encode()).hexdigest()


def _find_seed_for(setting: str, start: int, used: set[int]) -> int:
    seed = start
    while seed in used or choose_arm_turn(seed) != setting:
        seed += 1
    return seed


def materialize(out_dir: Path, seed_start: int = 7319) -> dict[str, Any]:
    """Execute both Racket settings and retain public/private bounded evidence."""
    from arc_repl.racket_bridge import RacketBridge
    from arcpuzzles import Catalog

    if out_dir.exists():
        raise FileExistsError(f"choose a new evidence directory: {out_dir}")
    out_dir.mkdir(parents=True)
    public_dir = out_dir / "public"
    rule_dir = out_dir / "rules"
    public_dir.mkdir()
    rule_dir.mkdir()

    root = Path(__file__).resolve().parents[4]
    source = Path(__file__).resolve()
    generator_source = _generator_path()
    catalog = Catalog(root)
    bridge = RacketBridge(max_calls_before_restart=128, timeout=30.0)
    settings: dict[str, Any] = {}
    used: set[int] = set()
    try:
        for offset, setting in enumerate(ALLOWED_ARM_TURNS):
            seed = _find_seed_for(setting, seed_start + offset, used)
            used.add(seed)
            episode = build_episode(seed, arm_turn=setting)
            program = program_for(setting)
            rival = next(value for value in ALLOWED_ARM_TURNS if value != setting)
            rival_program = program_for(rival)
            executed: list[dict[str, Any]] = []
            inputs: list[list[list[int]]] = []

            for split in ("train", "test"):
                for pair_index, pair in enumerate(episode[split]):
                    input_grid = pair["input"]
                    actual = apply_racket(bridge, program, input_grid)
                    rival_output = apply_racket(bridge, rival_program, input_grid)
                    python_output = apply_python(input_grid, setting)
                    if actual != python_output or actual != pair["output"]:
                        raise AssertionError(
                            f"Racket/Python mismatch for {setting} {split}[{pair_index}]"
                        )
                    pair["output"] = actual
                    inputs.append(input_grid)
                    executed.append({
                        "split": split,
                        "pair_index": pair_index,
                        "input_sha256": _sha256_json(input_grid),
                        "racket_output": actual,
                        "rival_setting": rival,
                        "rival_racket_output": rival_output,
                        "settings_disagree": actual != rival_output,
                    })

            canonical_parity = None
            if setting == DEFAULT_ARM_TURN:
                reference = catalog.apply(TASK_ID, inputs, reference="canonical", timeout=180)
                if any(item.get("error") for item in reference["results"]):
                    raise RuntimeError(f"canonical reference failed: {reference}")
                reference_outputs = [item["output"] for item in reference["results"]]
                actual_outputs = [item["racket_output"] for item in executed]
                canonical_parity = reference_outputs == actual_outputs
                if not canonical_parity:
                    raise AssertionError("default half_turn prototype diverges from canonical Racket")

            findings = parameter_rival_findings(episode)
            if findings:
                raise AssertionError("; ".join(findings))
            if not all(item["settings_disagree"] for item in executed):
                raise AssertionError(f"some {setting} pairs do not distinguish {rival}")

            rule_path = rule_dir / f"arm_turn_{setting}.rkt"
            rule_path.write_text(program + "\n")
            public = public_challenge(episode)
            public_path = public_dir / f"arm_turn_{setting}.json"
            public_path.write_text(json.dumps(public, indent=2, sort_keys=True) + "\n")
            settings[setting] = {
                "seed": seed,
                "selected_once_by_seed": choose_arm_turn(seed),
                "is_canonical_default": setting == DEFAULT_ARM_TURN,
                "program_path": str(rule_path.relative_to(out_dir)),
                "program_text": program,
                "program_sha256": program_sha256(setting),
                "episode": episode,
                "episode_sha256": _sha256_json(episode),
                "public_path": str(public_path.relative_to(out_dir)),
                "public_sha256": hashlib.sha256(public_path.read_bytes()).hexdigest(),
                "executed_pairs": executed,
                "all_pairs_match_racket": True,
                "every_demo_refutes_rival": all(
                    item["settings_disagree"] for item in executed if item["split"] == "train"
                ),
                "query_refutes_rival": all(
                    item["settings_disagree"] for item in executed if item["split"] == "test"
                ),
                "canonical_default_parity": canonical_parity,
            }
        runtime_identity = bridge.runtime_identity
    finally:
        bridge.shutdown()

    evidence = {
        "schema": "arcpuzzles-parametric-arm-turn-evidence-v1",
        "status": "prototype",
        "task_id": TASK_ID,
        "prototype_version": PROTOTYPE_VERSION,
        "parameter": {
            "name": "arm_turn",
            "allowed_values": list(ALLOWED_ARM_TURNS),
            "canonical_default": DEFAULT_ARM_TURN,
            "selection": "SHA-256(task_id|arm_turn|seed), once per episode",
            "input_constraints": (
                "Same lawful creature inputs as the selected generator; four distinct arm "
                "colors guarantee half_turn and preserve differ."
            ),
            "invariant_reasoning": [
                "detect each color-4 cross and its connected color-1 tail",
                "infer tail direction and move the full creature to the opposite wall",
                "translate the tail intact and repaint the cyan background",
            ],
            "varied_reasoning": "whether arm colors rotate 180 degrees or preserve orientation",
        },
        "prototype_source_sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
        "generator_source_sha256": hashlib.sha256(generator_source.read_bytes()).hexdigest(),
        "runtime_identity": runtime_identity,
        "settings": settings,
        "limitations": [
            "Two settings and one retained episode per setting; this is not a production API or approval.",
            "The selected generator and canonical authority remain fixed at half_turn.",
            "Demonstrations refute only the declared preserve/half_turn rival; arbitrary programs are not exhausted.",
        ],
    }
    evidence_path = out_dir / "evidence.json"
    evidence_path.write_text(json.dumps(evidence, indent=2, sort_keys=True) + "\n")
    command = {
        "cwd": "WORK/repo",
        "argv": [
            "python3", "generators/0d1deab2505c/workspace/parametric/prototype.py",
            "--out", str(out_dir), "--seed-start", str(seed_start),
        ],
        "evidence_sha256": hashlib.sha256(evidence_path.read_bytes()).hexdigest(),
    }
    (out_dir / "command.json").write_text(json.dumps(command, indent=2, sort_keys=True) + "\n")
    return evidence


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", required=True, type=Path)
    parser.add_argument("--seed-start", type=int, default=7319)
    args = parser.parse_args()
    evidence = materialize(args.out, seed_start=args.seed_start)
    print(json.dumps({
        "status": evidence["status"],
        "task_id": TASK_ID,
        "out": str(args.out),
        "settings": {
            name: {
                "seed": record["seed"],
                "program_sha256": record["program_sha256"],
                "every_demo_refutes_rival": record["every_demo_refutes_rival"],
                "canonical_default_parity": record["canonical_default_parity"],
            }
            for name, record in evidence["settings"].items()
        },
    }, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
