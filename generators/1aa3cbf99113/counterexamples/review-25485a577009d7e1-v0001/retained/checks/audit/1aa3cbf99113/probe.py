def components(grid):
    seen = set()
    sizes = []
    for r, row in enumerate(grid):
        for c, v in enumerate(row):
            if not v or (r, c) in seen:
                continue
            pending = [(r, c)]
            seen.add((r, c))
            n = 0
            while pending:
                a, b = pending.pop()
                n += 1
                for x, y in ((a-1,b), (a+1,b), (a,b-1), (a,b+1)):
                    if 0 <= x < len(grid) and 0 <= y < len(grid[0]) and (x,y) not in seen and grid[x][y] == v:
                        seen.add((x,y))
                        pending.append((x,y))
            sizes.append(n)
    return sizes

