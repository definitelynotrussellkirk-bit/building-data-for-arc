#!/usr/bin/env python3
"""Proposed, unapproved output-colour variant; no production API changes.

Run from an extracted packet through review.py run (see README.md).
Every label and rival prediction is evaluated by the included Racket bridge.
"""
from __future__ import annotations

import argparse
import copy
import hashlib
import json
import random
import sys
from pathlib import Path

from arc_repl.racket_bridge import RacketBridge, racket_runtime_status
from reviewer_support import canonical_pairs, canonical_path, find_root, normalize_grid


TASK_ID = "23a0c42b8a1c"
VERSION = "proposed-output-colour-v1"
ALLOWED_OUTPUT_COLOURS = (8, 2)
DEFAULT_OUTPUT_COLOUR = 8
CANONICAL_SHA256 = "5af80c67d3907183931a179f7ff8ad18fc3c41ab97c1030589b0a4649a5ca7c7"
CANONICAL_RULE_HASH = "5af80c67d390"
RECOLOUR_SITE = "(extract-union g objs (list target) 8)"


def _sha256(value):
    return hashlib.sha256(value.encode() if isinstance(value, str) else value).hexdigest()


def _json(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":"))


def grid_sha256(grid):
    return _sha256(_json(normalize_grid(grid)))


def _validate_seed(seed):
    if type(seed) is not int or not 0 <= seed < 2**63:
        raise ValueError("seed must be an integer in 0..2**63-1")


def _check_source(source):
    if not isinstance(source, str) or _sha256(source) != CANONICAL_SHA256:
        raise ValueError("canonical source SHA256 does not match the pinned rule")
    if source.count(RECOLOUR_SITE) != 1:
        raise ValueError("canonical source must contain exactly one guarded recolouring site")
    return source


def canonical_source(*, root=None):
    root = find_root(__file__) if root is None else Path(root)
    sources = set()
    with canonical_path(root).open(encoding="utf-8") as handle:
        for line in handle:
            if line.strip():
                row = json.loads(line)
                if row.get("task_id") == TASK_ID:
                    sources.add(row.get("program_solution"))
    if len(sources) != 1:
        raise ValueError("expected exactly one distinct canonical source for " + TASK_ID)
    return _check_source(sources.pop())


def materialize_rule(output_colour=DEFAULT_OUTPUT_COLOUR, *, root=None, source=None):
    if type(output_colour) is not int or output_colour not in ALLOWED_OUTPUT_COLOURS:
        raise ValueError("output_colour must be the integer 8 or 2")
    canonical = canonical_source(root=root) if source is None else _check_source(source)
    return canonical.replace(RECOLOUR_SITE, f"(extract-union g objs (list target) {output_colour})", 1)


def rule_callable(source):
    """Bind g around this pinned body; intentionally not a general DSL parser.

    The shared wrap_rule imports a scripts package unavailable in direct packet
    payloads. This exact source contains no shorthand or free h/w variables.
    Verify the original hash after reversing the sole allowed substitution,
    then preserve every byte of its rule body inside a lambda.
    """
    if not isinstance(source, str):
        raise ValueError("canonical source SHA256 requires Racket text")
    original = source.replace("(extract-union g objs (list target) 2)", RECOLOUR_SITE, 1)
    _check_source(original)
    return "(lambda (g) " + source[len("(rule! "):-1] + ")"


def execute_rule(source, grid, *, bridge=None):
    """Apply the actual wrapped Racket expression; no Python rule mirror."""
    grid = normalize_grid(grid)
    literal = "'(" + " ".join("(" + " ".join(map(str, row)) + ")" for row in grid) + ")"
    expression = f"({rule_callable(source)} {literal})"
    if bridge is None:
        with RacketBridge() as owned:
            return normalize_grid(owned.eval_text(expression))
    return normalize_grid(bridge.eval_text(expression))


def fixtures():
    """Four original hand-authored inputs; no selected-generator dependency.

    Lists are explicitly painted, not generated by an alternative answer rule.
    All have one colour-1 component and two unequal-sized cardinal neighbours.
    Input constraints are identical for both output-colour settings. Ties are
    outside this prototype's executable domain: the canonical tie branch fails
    with the included runtime, and neither its source nor the runtime is edited.
    """
    specifications = [
        ("small_L_with_remote_singleton", 8, 9, {
            1: [(3, 3)],
            3: [(1, 3), (1, 4), (2, 3)],
            4: [(4, 3), (4, 4), (5, 3), (5, 4)],
            6: [(0, 0)],
        }),
        ("left_domino_with_diagonal_singleton", 8, 9, {
            1: [(3, 4)],
            5: [(3, 2), (3, 3)],
            7: [(4, 4), (4, 5), (5, 4), (5, 5), (6, 4)],
            6: [(2, 5)],
        }),
        ("upper_L_smaller_than_right_line", 9, 10, {
            1: [(4, 4)],
            3: [(2, 4), (2, 5), (3, 4)],
            5: [(4, 5), (4, 6), (4, 7), (4, 8)],
        }),
        ("C_shape_with_foreign_cell_inside_crop", 11, 11, {
            1: [(5, 4)],
            3: [(2, 4), (2, 5), (2, 6), (3, 4), (4, 4), (4, 5), (4, 6)],
            6: [(3, 5)],
            7: [(r, c) for r in range(6, 9) for c in range(4, 7)],
        }),
    ]
    result = []
    for name, height, width, objects in specifications:
        grid = [[0] * width for _ in range(height)]
        for colour, cells in objects.items():
            for row, column in cells:
                if grid[row][column] != 0:
                    raise ValueError("fixture contains overlapping objects")
                grid[row][column] = colour
        result.append({"fixture_id": name, "input": grid})
    return result


def parameters_for_seed(seed):
    _validate_seed(seed)
    # Exactly one parameter draw per episode; input ordering has a separate RNG.
    return {"output_colour": random.Random(seed).choice(ALLOWED_OUTPUT_COLOURS)}


def make_episode(seed, *, root=None, bridge=None):
    parameters = parameters_for_seed(seed)
    if bridge is None:
        with RacketBridge() as owned:
            return _make_episode(seed, parameters, root=root, bridge=owned)
    return _make_episode(seed, parameters, root=root, bridge=bridge)


def _make_episode(seed, parameters, *, root, bridge):
    canonical = canonical_source(root=root)
    rules = {colour: materialize_rule(colour, source=canonical) for colour in ALLOWED_OUTPUT_COLOURS}
    inputs = fixtures()
    random.Random(f"{TASK_ID}:fixture-order:v1:{seed}").shuffle(inputs)
    outputs = {
        colour: [execute_rule(source, pair["input"], bridge=bridge) for pair in inputs]
        for colour, source in rules.items()
    }
    colour = parameters["output_colour"]
    pairs = [dict(pair, output=output, input_sha256=grid_sha256(pair["input"]),
                  output_sha256=grid_sha256(output))
             for pair, output in zip(inputs, outputs[colour], strict=True)]
    rival_rows = []
    ambiguities = []
    for rival_colour in ALLOWED_OUTPUT_COLOURS:
        train_mismatches = [i for i in range(3) if outputs[rival_colour][i] != outputs[colour][i]]
        query_mismatches = [0] if outputs[rival_colour][3] != outputs[colour][3] else []
        status = ("refuted_by_demonstrations" if train_mismatches else
                  "ambiguous_query" if query_mismatches else "matches_episode")
        row = {"output_colour": rival_colour, "racket_sha256": _sha256(rules[rival_colour]),
               "status": status, "demonstration_mismatch_indices": train_mismatches,
               "query_mismatch_indices": query_mismatches,
               "train_predictions": outputs[rival_colour][:3],
               "query_predictions": outputs[rival_colour][3:]}
        rival_rows.append(row)
        if status == "ambiguous_query":
            ambiguities.append(row)
    source = rules[colour]
    return {
        "schema": "arcpuzzles-proposed-parametric-episode-v1",
        "task_id": TASK_ID, "prototype_version": VERSION,
        "status": "proposed_unapproved", "approved": False, "seed": seed,
        "parameters": parameters,
        "parameter_selection": "one random.Random(seed).choice((8, 2)) draw before any pair",
        "prototype_sha256": _sha256(Path(__file__).read_bytes()),
        "canonical_rule_hash": CANONICAL_RULE_HASH, "canonical_source_sha256": CANONICAL_SHA256,
        "racket_source": source, "racket_sha256": _sha256(source),
        "racket_callable": rule_callable(source), "racket_callable_sha256": _sha256(rule_callable(source)),
        "racket_path": f"private/rules/output-colour-{colour}.rkt",
        "train": pairs[:3], "test": pairs[3:],
        "parameter_rivals": rival_rows, "ambiguities": ambiguities,
        "racket_evaluations": 8,
    }


def public_challenge(episode):
    """Construct an explicit allowlist view; copy mutable grid arrays."""
    return copy.deepcopy({
        "train": [{"input": p["input"], "output": p["output"]} for p in episode["train"]],
        "test": [{"input": p["input"]} for p in episode["test"]],
    })


def _write_json(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def write_evidence(seeds, *, out, root=None):
    """Retain finite executable evidence in a new directory; failures stay visible."""
    seeds = tuple(seeds)
    if not seeds or len(set(seeds)) != len(seeds):
        raise ValueError("provide at least one distinct episode seed")
    for seed in seeds:
        _validate_seed(seed)
    root = find_root(__file__) if root is None else Path(root).resolve()
    out = Path(out)
    out.mkdir(parents=True, exist_ok=False)
    try:
        return _write_evidence(seeds, out=out, root=root)
    except Exception as exc:
        _write_json(out / "failure.json", {"status": "error", "error_type": type(exc).__name__,
                                           "error": str(exc), "seeds": seeds})
        raise


def _write_evidence(seeds, *, out, root):
    source_path = Path(__file__).resolve()
    test_path = root / f"generators/{TASK_ID}/tests/test_parametric_variant.py"
    snapshot = out / "private/source_snapshot"
    snapshot.mkdir(parents=True)
    sources = []
    for path in (source_path, test_path):
        if path.is_file():
            (snapshot / path.name).write_bytes(path.read_bytes())
            sources.append({"path": str(path.relative_to(root)), "sha256": _sha256(path.read_bytes()),
                            "snapshot": f"private/source_snapshot/{path.name}"})
    runtime_files = []
    for name in ("reviewer_support.py", "arc_repl/racket_bridge.py",
                 "arc_repl/racket_prelude/arc-prelude.rkt"):
        path = root / "shared/runtime" / name
        runtime_files.append({"path": str(path.relative_to(root)), "sha256": _sha256(path.read_bytes())})
    canonical = canonical_source(root=root)
    rule_dir = out / "private/rules"
    rule_dir.mkdir(parents=True)
    rule_rows = []
    for colour in ALLOWED_OUTPUT_COLOURS:
        source = materialize_rule(colour, source=canonical)
        rule_path = rule_dir / f"output-colour-{colour}.rkt"
        rule_path.write_text(source, encoding="utf-8")
        rule_rows.append({"output_colour": colour, "path": str(rule_path.relative_to(out)),
                          "sha256": _sha256(source), "callable_sha256": _sha256(rule_callable(source))})
    episode_rows, canonical_rows = [], []
    distinct_inputs = set()
    with RacketBridge() as bridge:
        witness_input = fixtures()[0]["input"]
        witness_outputs = {str(colour): execute_rule(materialize_rule(colour, source=canonical),
                                                   witness_input, bridge=bridge)
                           for colour in ALLOWED_OUTPUT_COLOURS}
        if witness_outputs["8"] == witness_outputs["2"]:
            raise AssertionError("parameter settings failed to change the witness output")
        _write_json(out / "private/distinguishing_witness.json",
                    {"input": witness_input, "input_sha256": grid_sha256(witness_input),
                     "outputs_by_output_colour": witness_outputs, "rules": rule_rows})
        for pair in canonical_pairs(TASK_ID, root=root, labeled_only=True):
            actual = execute_rule(canonical, pair["input"], bridge=bridge)
            row = dict(pair, actual=actual, matches=actual == pair["output"],
                       input_sha256=grid_sha256(pair["input"]), output_sha256=grid_sha256(actual))
            canonical_rows.append(row)
        _write_json(out / "private/canonical_original_check.json", canonical_rows)
        if not canonical_rows or not all(row["matches"] for row in canonical_rows):
            raise AssertionError("original setting did not reproduce every labelled canonical pair")
        for index, seed in enumerate(seeds):
            episode = make_episode(seed, root=root, bridge=bridge)
            replay = make_episode(seed, root=root, bridge=bridge)
            deterministic = episode == replay
            if not deterministic:
                _write_json(out / f"private/episode-{index:03d}-replay-failure.json", replay)
                raise AssertionError("same-seed episode replay changed")
            public_path = f"public/episode-{index:03d}.json"
            private_path = f"private/episode-{index:03d}.json"
            _write_json(out / public_path, public_challenge(episode))
            _write_json(out / private_path, episode)
            distinct_inputs.update(p["input_sha256"] for p in episode["train"] + episode["test"])
            episode_rows.append({"seed": seed, "parameters": episode["parameters"],
                                 "public_path": public_path, "private_path": private_path,
                                 "deterministic_replay": deterministic, "episode_sha256": _sha256(_json(episode)),
                                 "parameter_rivals": [{k: row[k] for k in (
                                     "output_colour", "status", "demonstration_mismatch_indices",
                                     "query_mismatch_indices")} for row in episode["parameter_rivals"]]})
    files = [{"path": str(path.relative_to(out)), "sha256": _sha256(path.read_bytes())}
             for path in sorted(out.rglob("*")) if path.is_file()]
    report = {
        "schema": "arcpuzzles-proposed-parametric-evidence-v1", "status": "proposed_unapproved",
        "approved": False, "task_id": TASK_ID, "prototype_version": VERSION,
        "parameter": {"name": "output_colour", "allowed_values": list(ALLOWED_OUTPUT_COLOURS),
                      "original_default": DEFAULT_OUTPUT_COLOUR, "input_constraints_depend_on_parameter": False},
        "input_scope": "four original hand-authored inputs with two unequal-sized marker neighbours; per-seed input order only",
        "sources": sources, "runtime_files": runtime_files, "runtime": racket_runtime_status(),
        "rules": rule_rows, "episodes": episode_rows, "files": files,
        "canonical_rule_hash": CANONICAL_RULE_HASH, "canonical_source_sha256": CANONICAL_SHA256,
        "counts": {"episodes": len(seeds), "train_pairs": 3 * len(seeds), "query_pairs": len(seeds),
                   "distinct_input_grids": len(distinct_inputs), "settings_exercised": 2,
                   "episode_settings_exercised": len({r["parameters"]["output_colour"] for r in episode_rows}),
                   "canonical_pairs_checked": len(canonical_rows),
                   "racket_evaluations_including_deterministic_replays": 16 * len(seeds) + len(canonical_rows) + 2,
                   "parameter_rival_episode_checks": 2 * len(seeds),
                   "ambiguous_parameter_rivals": sum(r["status"] == "ambiguous_query"
                       for e in episode_rows for r in e["parameter_rivals"])},
        "limitations": ["Proposed prototype only; no variant approval or production API change.",
                        "Four authored input grids and the recorded seeds; no distribution or all-seed claim.",
                        "Tied marker-neighbour sizes are excluded: the unchanged canonical tie branch raises in the included runtime.",
                        "Rival checks cover only output_colour in {8,2}, not every conceivable competing rule.",
                        "Canonical rule remains pinned; default preservation also checked on three labelled canonical pairs.",
                        "Input ordering varies by seed; this is not a replacement input generator."],
        "process_argv": list(sys.argv), "effective_cwd": str(Path.cwd()),
    }
    _write_json(out / "report.json", report)
    return report


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--seeds", nargs="+", type=int, default=[0, 1])
    parser.add_argument("--out", type=Path, required=True, help="new evidence directory")
    args = parser.parse_args(argv)
    report = write_evidence(args.seeds, out=args.out)
    print(json.dumps({"status": report["status"], "counts": report["counts"],
                      "report": str(args.out / "report.json")}, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
