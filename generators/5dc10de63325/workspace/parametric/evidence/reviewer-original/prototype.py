#!/usr/bin/env python3
"""Isolated fill-order rule prototype for ARC task 5dc10de63325.

The selected production generator and canonical Racket authority remain
unchanged.  This prototype varies only the order in which a counted 2x2 glyph
is filled before that glyph is repeated in the four quadrants of the 5x5
zero-cross output.  The hidden setting is selected once per episode.

All retained episode labels are generated by executing the exact materialized
Racket program through the packet's protected Racket bridge.  ``python_reference``
is a test/debug mirror, not the retained labeling authority.
"""
from __future__ import annotations

import argparse
from copy import deepcopy
import hashlib
import json
import os
from pathlib import Path
import sys
from typing import Any

from puzzle_generators.base import stable_rng


TASK_ID = "5dc10de63325"
CANONICAL_RULE_HASH = "f2b1ab0d6fcb"
CANONICAL_SOURCE_SHA256 = "7a10e356fef67a39818753dde5902520c4f89b1bf646ada192200eb0da0ec8a3"
PROTOTYPE_VERSION = "fill-order-v1"
PARAMETER_NAME = "fill_order"
DEFAULT_FILL_ORDER = "bottom_row_first"
ALLOWED_FILL_ORDERS = (
    DEFAULT_FILL_ORDER,
    "right_column_first",
    "top_row_first",
)
FILL_ORDERS = {
    # Canonical: bottom-right, bottom-left, top-right, top-left.
    DEFAULT_FILL_ORDER: ((1, 1), (1, 0), (0, 1), (0, 0)),
    # Nearby alternative: bottom-right, top-right, bottom-left, top-left.
    "right_column_first": ((1, 1), (0, 1), (1, 0), (0, 0)),
    # Nearby alternative: top-left, top-right, bottom-left, bottom-right.
    "top_row_first": ((0, 0), (0, 1), (1, 0), (1, 1)),
}
PARAMETER_SPEC = {
    PARAMETER_NAME: {
        "type": "enum",
        "allowed": list(ALLOWED_FILL_ORDERS),
        "default": DEFAULT_FILL_ORDER,
        "chosen": "once per episode from the deterministic episode seed",
        "invariant_reasoning": [
            "count cyan cells",
            "floor-divide the count by four",
            "fill that many positions of one 2x2 glyph",
            "repeat the glyph in four quadrants around a zero cross",
        ],
        "input_constraints": (
            "ordinary canonical-generator inputs with colors {0,8}, at least "
            "one zero, dimensions 5..18, and cyan counts 4..19"
        ),
    }
}

# Three demonstrations distinguish all settings; the query revisits q2 with a
# different remainder and geometry so the episode tests transfer, not copying.
DEMO_COUNTS = (5, 9, 13)
QUERY_COUNT = 10
PAIR_DISTRIBUTIONS = ("block", "scattered", "snake", "clustered")
PAIR_DIFFICULTIES = ("easy", "medium", "hard", "medium")
PAIR_DIMENSIONS = ((6, 6), (7, 8), (9, 7), (8, 9))


def digest(value: Any) -> str:
    """Stable SHA-256 for JSON-compatible evidence values or raw text/bytes."""
    if isinstance(value, bytes):
        payload = value
    elif isinstance(value, str):
        payload = value.encode("utf-8")
    else:
        payload = json.dumps(
            value, sort_keys=True, ensure_ascii=False, separators=(",", ":")
        ).encode("utf-8")
    return hashlib.sha256(payload).hexdigest()


def file_digest(path: Path) -> str:
    hasher = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            hasher.update(block)
    return hasher.hexdigest()


def _validate_seed(seed: Any) -> int:
    if type(seed) is not int or seed < 0:
        raise TypeError("episode seed must be a nonnegative literal integer")
    return seed


def _validate_fill_order(fill_order: Any) -> str:
    if type(fill_order) is not str or fill_order not in ALLOWED_FILL_ORDERS:
        raise ValueError(
            f"{PARAMETER_NAME} must be one of {ALLOWED_FILL_ORDERS}, got {fill_order!r}"
        )
    return fill_order


def choose_parameters(seed: int) -> dict[str, str]:
    """Choose one hidden rule setting for the whole episode."""
    _validate_seed(seed)
    rng = stable_rng(seed, f"{TASK_ID}|parametric-rule", PROTOTYPE_VERSION)
    return {
        PARAMETER_NAME: ALLOWED_FILL_ORDERS[
            rng.randrange(len(ALLOWED_FILL_ORDERS))
        ]
    }


def _normalize_grid(grid: Any) -> list[list[int]]:
    if not isinstance(grid, list) or not grid:
        raise ValueError("grid must be a nonempty list")
    if not isinstance(grid[0], list) or not grid[0]:
        raise ValueError("grid rows must be nonempty lists")
    width = len(grid[0])
    if any(not isinstance(row, list) or len(row) != width for row in grid):
        raise ValueError("grid must be rectangular")
    if any(type(cell) is not int or not 0 <= cell <= 9 for row in grid for cell in row):
        raise ValueError("grid cells must be literal ARC integers 0..9")
    return [list(row) for row in grid]


def canonical_source(*, root: Path | str | None = None) -> str:
    """Load and content-pin the selected canonical Racket program."""
    from reviewer_support import canonical_path, find_root

    root_path = find_root(__file__) if root is None else Path(root).resolve()
    sources: set[str] = set()
    with canonical_path(root_path).open(encoding="utf-8") as handle:
        for line in handle:
            if not line.strip():
                continue
            row = json.loads(line)
            if row.get("task_id") == TASK_ID and isinstance(row.get("program_solution"), str):
                sources.add(row["program_solution"])
    if len(sources) != 1:
        raise ValueError(f"expected one canonical Racket source, found {len(sources)}")
    source = sources.pop()
    if digest(source) != CANONICAL_SOURCE_SHA256:
        raise ValueError("canonical source SHA-256 does not match the pinned rule")
    return source


def _tile_clause(bucket: int, order: tuple[tuple[int, int], ...]) -> str:
    if bucket not in (1, 2, 3, 4):
        raise ValueError("tile bucket must be 1..4")
    on = set(order[:bucket])
    rows = [[8 if (r, c) in on else 0 for c in range(2)] for r in range(2)]
    return (
        f"((= per-quad {bucket}) "
        f"(list (list {rows[0][0]} {rows[0][1]}) "
        f"(list {rows[1][0]} {rows[1][1]})))"
    )


def materialize_rule(
    fill_order: str = DEFAULT_FILL_ORDER,
    *,
    root: Path | str | None = None,
    source: str | None = None,
) -> str:
    """Return the exact Racket rule for one declared fill order."""
    setting = _validate_fill_order(fill_order)
    canonical = canonical_source(root=root) if source is None else source
    if not isinstance(canonical, str) or digest(canonical) != CANONICAL_SOURCE_SHA256:
        raise ValueError("source is not the pinned canonical Racket program")
    if setting == DEFAULT_FILL_ORDER:
        return canonical

    result = canonical
    canonical_order = FILL_ORDERS[DEFAULT_FILL_ORDER]
    selected_order = FILL_ORDERS[setting]
    for bucket in (1, 2, 3):
        old = _tile_clause(bucket, canonical_order)
        new = _tile_clause(bucket, selected_order)
        if result.count(old) != 1:
            raise ValueError(f"canonical tile clause q{bucket} is missing or ambiguous")
        result = result.replace(old, new, 1)
    if result == canonical:
        raise AssertionError("alternative setting failed to change the Racket program")
    return result


def restore_canonical(source: Any, *, root: Path | str | None = None) -> str:
    """Accept only one complete declared setting and restore the pinned source."""
    if not isinstance(source, str):
        raise TypeError("Racket source must be text")
    canonical = canonical_source(root=root)
    for setting in ALLOWED_FILL_ORDERS:
        if source == materialize_rule(setting, source=canonical):
            return canonical
    raise ValueError("source is not one of the declared complete fill-order rules")


def rule_callable(source: str, *, root: Path | str | None = None) -> str:
    restore_canonical(source, root=root)
    prefix = "(rule!"
    if not source.startswith(prefix) or not source.endswith(")"):
        raise ValueError("unexpected canonical rule wrapper")
    body = source[len(prefix) : -1].strip()
    if not body.startswith("(lambda (g)"):
        raise ValueError("expected one wrapped grid lambda")
    return body


def grid_literal(grid: Any) -> str:
    rows = _normalize_grid(grid)
    return "'(" + " ".join(
        "(" + " ".join(map(str, row)) + ")" for row in rows
    ) + ")"


def execute_rule(
    source: str,
    grid: Any,
    *,
    bridge: Any,
    root: Path | str | None = None,
) -> list[list[int]]:
    expression = f"({rule_callable(source, root=root)} {grid_literal(grid)})"
    return _normalize_grid(bridge.eval_text(expression))


def _glyph(bucket: int, order: tuple[tuple[int, int], ...]) -> list[list[int]]:
    bucket = max(0, min(4, bucket))
    on = set(order[:bucket])
    tile = [[8 if (r, c) in on else 0 for c in range(2)] for r in range(2)]
    return [
        [
            0
            if row == 2 or col == 2
            else tile[row if row < 2 else row - 3][col if col < 2 else col - 3]
            for col in range(5)
        ]
        for row in range(5)
    ]


def python_reference(
    grid: Any,
    *,
    fill_order: str = DEFAULT_FILL_ORDER,
) -> list[list[int]]:
    """Debug mirror of the bounded rule family; not a retained label source."""
    rows = _normalize_grid(grid)
    setting = _validate_fill_order(fill_order)
    count = sum(cell == 8 for row in rows for cell in row)
    return _glyph(count // 4, FILL_ORDERS[setting])


def public_challenge(episode: dict[str, Any]) -> dict[str, Any]:
    """Remove the hidden setting, seed, code, alternatives and query answer."""
    train = deepcopy(episode["train"])
    test = [{"input": deepcopy(pair["input"])} for pair in episode["test"]]
    return {
        "schema": "arc-parametric-public-challenge-v1",
        "task_id": TASK_ID,
        "prototype_version": PROTOTYPE_VERSION,
        "train": train,
        "test": test,
    }


def _first_seed_for(setting: str) -> int:
    _validate_fill_order(setting)
    for seed in range(10000):
        if choose_parameters(seed)[PARAMETER_NAME] == setting:
            return seed
    raise AssertionError(f"no seed found for {setting}")


def _build_inputs(generator: Any, *, seed: int) -> list[list[list[int]]]:
    counts = (*DEMO_COUNTS, QUERY_COUNT)
    grids = []
    for index, count in enumerate(counts):
        height, width = PAIR_DIMENSIONS[index]
        grid = generator.generate(
            seed * 1009 + 137,
            index,
            difficulty=PAIR_DIFFICULTIES[index],
            grid_h=height,
            grid_w=width,
            n_cyans=count,
            distribution=PAIR_DISTRIBUTIONS[index],
        )
        errors = generator.self_check(grid, difficulty=PAIR_DIFFICULTIES[index])
        if errors:
            raise AssertionError(f"prototype input is outside the ordinary grammar: {errors}")
        if sum(cell == 8 for row in grid for cell in row) != count:
            raise AssertionError("selected generator did not honor the exact count")
        grids.append(grid)
    return grids


def build_episode(
    generator: Any,
    bridge: Any,
    *,
    seed: int,
    canonical: str,
    root: Path | str,
) -> dict[str, Any]:
    """Build one private episode and execute every declared setting on each pair."""
    parameters = choose_parameters(seed)
    selected = parameters[PARAMETER_NAME]
    sources = {
        setting: materialize_rule(setting, source=canonical)
        for setting in ALLOWED_FILL_ORDERS
    }
    grids = _build_inputs(generator, seed=seed)
    all_outputs: list[dict[str, list[list[int]]]] = []
    pairs = []
    for grid in grids:
        outputs = {
            setting: execute_rule(source, grid, bridge=bridge, root=root)
            for setting, source in sources.items()
        }
        for setting, output in outputs.items():
            mirror = python_reference(grid, fill_order=setting)
            if output != mirror:
                raise AssertionError(f"Python mirror disagrees with executed Racket for {setting}")
        all_outputs.append(outputs)
        pairs.append({"input": grid, "output": outputs[selected]})

    episode = {"train": pairs[: len(DEMO_COUNTS)], "test": pairs[len(DEMO_COUNTS) :]}
    demo_distinction = {}
    for rival in ALLOWED_FILL_ORDERS:
        if rival == selected:
            continue
        demo_distinction[rival] = any(
            all_outputs[index][rival] != pairs[index]["output"]
            for index in range(len(DEMO_COUNTS))
        )
    if not all(demo_distinction.values()):
        raise AssertionError("demonstrations do not distinguish every alternative setting")

    return {
        "schema": "arc-parametric-episode-evidence-v1",
        "task_id": TASK_ID,
        "prototype_version": PROTOTYPE_VERSION,
        "seed": seed,
        "parameters": parameters,
        "parameter_spec": PARAMETER_SPEC,
        "episode": episode,
        "all_setting_outputs": all_outputs,
        "racket_programs": sources,
        "racket_sha256": {setting: digest(source) for setting, source in sources.items()},
        "checks": {
            "parameter_chosen_once_for_episode": True,
            "three_demonstrations_one_query": (
                len(episode["train"]) == 3 and len(episode["test"]) == 1
            ),
            "all_labels_from_executed_racket": True,
            "python_mirror_parity": True,
            "default_source_byte_exact": sources[DEFAULT_FILL_ORDER] == canonical,
            "demos_distinguish_each_alternative": demo_distinction,
            "query_answer_retained_privately": "output" in episode["test"][0],
        },
    }


def canonical_replay(
    bridge: Any,
    source: str,
    *,
    root: Path | str,
) -> dict[str, Any]:
    from reviewer_support import canonical_pairs

    pairs = canonical_pairs(TASK_ID, root=root, labeled_only=True)
    mismatches = []
    for pair in pairs:
        actual = execute_rule(source, pair["input"], bridge=bridge, root=root)
        if actual != pair["output"]:
            mismatches.append(
                {
                    "variant": pair["variant"],
                    "split": pair["split"],
                    "pair_index": pair["pair_index"],
                }
            )
    return {"pairs": len(pairs), "mismatches": mismatches, "passed": not mismatches}


def _write_json(path: Path, value: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def build_evidence(out_dir: Path) -> dict[str, Any]:
    """Create source-bound public/private prototype evidence under a new directory."""
    from arc_repl.racket_bridge import RacketBridge, racket_runtime_status
    from reviewer_support import find_root, load_selected_generator

    out = out_dir.resolve()
    if out.exists():
        raise FileExistsError(f"refusing to overwrite evidence directory: {out}")
    public_dir = out / "public"
    private_dir = out / "private"
    rules_dir = private_dir / "rules"
    public_dir.mkdir(parents=True)
    rules_dir.mkdir(parents=True)

    root = find_root(__file__)
    generator, generator_path, generator_sha256 = load_selected_generator(TASK_ID, root=root)
    canonical = canonical_source(root=root)
    sources = {
        setting: materialize_rule(setting, source=canonical)
        for setting in ALLOWED_FILL_ORDERS
    }
    for setting, source in sources.items():
        rule_path = rules_dir / f"fill-order-{setting}.rkt"
        rule_path.write_text(source + "\n", encoding="utf-8")

    command = {"cwd": os.getcwd(), "argv": [sys.executable, *sys.argv]}
    source_dir = Path(__file__).resolve().parent
    episodes_summary = []
    with RacketBridge(timeout=30, max_calls_before_restart=64) as bridge:
        replay = canonical_replay(
            bridge, sources[DEFAULT_FILL_ORDER], root=root
        )
        if not replay["passed"]:
            raise AssertionError("default setting failed canonical replay")
        runtime_identity = bridge.runtime_identity

        for setting in ALLOWED_FILL_ORDERS:
            seed = _first_seed_for(setting)
            evidence = build_episode(
                generator,
                bridge,
                seed=seed,
                canonical=canonical,
                root=root,
            )
            if evidence["parameters"][PARAMETER_NAME] != setting:
                raise AssertionError("seed search and episode setting disagree")
            challenge = public_challenge(evidence["episode"])
            public_path = public_dir / f"episode-{setting}.json"
            private_path = private_dir / f"episode-{setting}.json"
            _write_json(public_path, challenge)
            evidence.update(
                {
                    "public_challenge": str(public_path.relative_to(out)),
                    "public_challenge_sha256": file_digest(public_path),
                    "canonical_replay": replay,
                    "selected_generator_path": str(Path(generator_path).resolve().relative_to(root)),
                    "source_hashes": {
                        "prototype.py": file_digest(source_dir / "prototype.py"),
                        "selected_generator.py": generator_sha256,
                        "canonical_source": digest(canonical),
                    },
                    "command": command,
                    "runtime_identity": runtime_identity,
                }
            )
            _write_json(private_path, evidence)
            episodes_summary.append(
                {
                    "setting": setting,
                    "seed": seed,
                    "public_challenge": str(public_path.relative_to(out)),
                    "public_challenge_sha256": file_digest(public_path),
                    "private_evidence": str(private_path.relative_to(out)),
                    "private_evidence_sha256": file_digest(private_path),
                    "selected_racket_sha256": evidence["racket_sha256"][setting],
                    "checks": evidence["checks"],
                }
            )

    summary = {
        "schema": "arc-parametric-prototype-summary-v1",
        "task_id": TASK_ID,
        "status": "prototype",
        "prototype_version": PROTOTYPE_VERSION,
        "selected_canonical_execution_path_unchanged": True,
        "canonical_rule_hash": CANONICAL_RULE_HASH,
        "canonical_source_sha256": digest(canonical),
        "parameter_spec": PARAMETER_SPEC,
        "settings_covered": [row["setting"] for row in episodes_summary],
        "canonical_replay": replay,
        "episodes": episodes_summary,
        "racket_runtime": racket_runtime_status(),
        "command": command,
        "limitations": [
            "This is an isolated authoring prototype, not a production rule API or training approval.",
            "Only three bounded fill orders and one retained episode per setting were executed.",
            "The retained grammar deliberately includes q1, q2 and q3 demonstrations; fewer demonstrations or other filtering policies were not validated.",
            "Only the declared fill-order rivals were checked; universal identifiability is not claimed.",
        ],
    }
    summary["passed"] = (
        set(summary["settings_covered"]) == set(ALLOWED_FILL_ORDERS)
        and replay["passed"]
        and all(
            row["checks"]["all_labels_from_executed_racket"]
            and row["checks"]["default_source_byte_exact"]
            and all(row["checks"]["demos_distinguish_each_alternative"].values())
            for row in episodes_summary
        )
    )
    _write_json(out / "summary.json", summary)
    manifest = {
        "schema": "arc-parametric-evidence-manifest-v1",
        "task_id": TASK_ID,
        "prototype_version": PROTOTYPE_VERSION,
        "files": [
            {"path": str(path.relative_to(out)), "sha256": file_digest(path)}
            for path in sorted(out.rglob("*"))
            if path.is_file()
        ],
    }
    _write_json(out / "manifest.json", manifest)
    return summary


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out-dir", type=Path, required=True)
    args = parser.parse_args()
    try:
        summary = build_evidence(args.out_dir)
    except FileExistsError as exc:
        parser.error(str(exc))
    print(json.dumps(summary, indent=2, sort_keys=True))
    return 0 if summary["passed"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
