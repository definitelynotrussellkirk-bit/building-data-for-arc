def schedule_profile(seed: int, sample_index: int, difficulty=None) -> str:
    """A period-three teaching schedule independent of canvas sampling.

    Every three consecutive accepted examples include a 4x4 canonical-shaped
    object and both a wider and a taller lawful counterexample to the strongest
    canonical-fitting size shortcut.
    """
    del seed, difficulty
    return SCHEDULE_PROFILES[sample_index % len(SCHEDULE_PROFILES)]


def _profile_options(difficulty) -> tuple[str, ...]:
    """Keep the full override domain in every band while shifting density."""
    all_profiles = tuple(SCENE_PROFILES)
    if difficulty == "easy":
        return all_profiles + ("7x9",) * 7 + ("11x9",) * 3
    if difficulty == "medium":
        return all_profiles + ("11x9",) * 2 + ("11x10",) * 7
    if difficulty == "hard":
        return all_profiles + ("11x10",) * 2 + ("11x15",) * 7
    return all_profiles


def _capacity(profile: str) -> int:
    if profile == "7x9":
        return 1
    if profile == "11x15":
        return 3
    return 2


def _rectangle_count(profile: str, sample_index: int, difficulty) -> int:
    """Deterministic curriculum density, capped by a constructive layout."""
    capacity = _capacity(profile)
    if capacity == 1:
        return 1
    phase = (sample_index // len(SCHEDULE_PROFILES)) % 4
    if difficulty == "easy":
        return 2 if phase == 3 else 1
    if difficulty == "medium":
        return 1 if phase == 0 else min(2, capacity)
    if difficulty == "hard":
        return capacity
    return 1 + (phase % capacity)


def _composition(total: int, parts: int, rng, *, forced_zero: int | None = None) -> list[int]:
    """Randomly distribute ``total`` indistinguishable slack cells."""
    if total < 0 or parts < 1:
        raise ValueError("invalid slack composition")
    result = [0] * parts
    choices = [index for index in range(parts) if index != forced_zero]
    if total and not choices:
        raise ValueError("cannot distribute positive slack with every part fixed")
    for _ in range(total):
        result[rng.choice(choices)] += 1
    return result


def _layout_rectangles(
    h: int,
    w: int,
    primary_size: tuple[int, int],
    count: int,
    *,
    sample_index: int,
    rng,
) -> list[tuple[int, int, int, int]]:
    """Construct 1-3 separated bboxes while preserving the primary size.

    For two objects a vertical stack is always feasible on every supported
    canvas; 11x15 sometimes uses a horizontal stack for additional variety.
    Three objects use a horizontal stack on 11x15.  Internal gaps are at least
    one background row/column, so outlines remain separate 4-connected objects.
    """
    if not (1 <= count <= 3):
        raise ValueError(f"unsupported rectangle count {count}")
    sizes = [primary_size] + [(4, 4)] * (count - 1)
    edge = OPEN_SIDES[(sample_index // len(SCHEDULE_PROFILES)) % len(OPEN_SIDES)]

    if count == 1:
        rh, rw = primary_size
        if edge == "up":
            r0, c0 = 0, rng.randint(0, w - rw)
        elif edge == "down":
            r0, c0 = h - rh, rng.randint(0, w - rw)
        elif edge == "left":
            r0, c0 = rng.randint(0, h - rh), 0
        else:
            r0, c0 = rng.randint(0, h - rh), w - rw
        return [(r0, c0, rh, rw)]

    horizontal = count == 3 or (w >= 15 and (sample_index // 3) % 2 == 1)
    if horizontal:
        # Put the primary at the requested outward edge when that edge is on
        # the stacking axis.  Otherwise its row touches the requested edge.
        if edge == "right":
            ordered = sizes[1:] + sizes[:1]
            primary_index = count - 1
        else:
            ordered = sizes
            primary_index = 0
        minimum = sum(rw for _, rw in ordered) + count - 1
        slack = w - minimum
        if slack < 0:
            raise RuntimeError("constructive horizontal layout no longer fits")
        fixed = 0 if edge == "left" else (count if edge == "right" else None)
        spaces = _composition(slack, count + 1, rng, forced_zero=fixed)
        result = []
        c0 = spaces[0]
        for index, (rh, rw) in enumerate(ordered):
            if index == primary_index and edge == "up":
                r0 = 0
            elif index == primary_index and edge == "down":
                r0 = h - rh
            else:
                r0 = rng.randint(0, h - rh)
            result.append((r0, c0, rh, rw))
            if index < count - 1:
                c0 += rw + 1 + spaces[index + 1]
        # The final margin is implicit; assert the construction consumed it.
        if c0 + ordered[-1][1] + spaces[-1] != w:
            raise RuntimeError("horizontal slack accounting error")
        return result

    # Vertical stack.  The primary can be first or last to realize an exact
    # top/bottom border touch; left/right touches use its independent column.
    if edge == "down":
        ordered = sizes[1:] + sizes[:1]
        primary_index = count - 1
    else:
        ordered = sizes
        primary_index = 0
    minimum = sum(rh for rh, _ in ordered) + count - 1
    slack = h - minimum
    if slack < 0:
        raise RuntimeError("constructive vertical layout no longer fits")
    fixed = 0 if edge == "up" else (count if edge == "down" else None)
    spaces = _composition(slack, count + 1, rng, forced_zero=fixed)
    result = []
    r0 = spaces[0]
    for index, (rh, rw) in enumerate(ordered):
        if index == primary_index and edge == "left":
            c0 = 0
        elif index == primary_index and edge == "right":
            c0 = w - rw
        else:
            c0 = rng.randint(0, w - rw)
        result.append((r0, c0, rh, rw))
        if index < count - 1:
            r0 += rh + 1 + spaces[index + 1]
    if r0 + ordered[-1][0] + spaces[-1] != h:
        raise RuntimeError("vertical slack accounting error")
    return result


def _gap_for_bbox(
    bbox: tuple[int, int, int, int], side: str, rng
) -> tuple[int, int]:
    r0, c0, rh, rw = bbox
    r1, c1 = r0 + rh - 1, c0 + rw - 1
    if side == "up":
        return r0, rng.randint(c0 + 1, c1 - 1)
    if side == "down":
        return r1, rng.randint(c0 + 1, c1 - 1)
    if side == "left":
        return rng.randint(r0 + 1, r1 - 1), c0
    if side == "right":
        return rng.randint(r0 + 1, r1 - 1), c1
    raise ValueError(f"unknown side {side!r}")


def generate(seed, sample_index, *, difficulty=None, **overrides):
    unknown = set(overrides) - set(AXES)
    if unknown:
        raise ValueError(f"unknown override axes: {sorted(unknown)}")
    if difficulty not in (None, "easy", "medium", "hard"):
        raise ValueError("difficulty must be None, 'easy', 'medium', or 'hard'")
    if "scene_profile" in overrides and overrides["scene_profile"] is not None:
        if type(overrides["scene_profile"]) is not str:
            raise TypeError("scene_profile override must be a string")
    if "background" in overrides and overrides["background"] is not None:
        if type(overrides["background"]) is not int:
            raise TypeError("background override must be an integer color (not bool)")

    ctx = gen_ctx(
        seed=seed,
        sample_index=sample_index,
        version=VERSION,
        task_id=TASK_ID,
        difficulty=difficulty,
        overrides=overrides,
    )
    profile = ctx.draw_choice("scene_profile", _profile_options(difficulty))
    background = ctx.draw_color("background", exclude={1, 2})
    h, w = SCENE_PROFILES[profile]
    primary_size = _PROFILE_SIZE[schedule_profile(seed, sample_index, difficulty)]
    count = _rectangle_count(profile, sample_index, difficulty)
    bboxes = _layout_rectangles(
        h,
        w,
        primary_size,
        count,
        sample_index=sample_index,
        rng=ctx.draw_rng("rectangle_layout"),
    )

    grid = full_grid(h, w, background)
    side_offset = ctx.draw_rng("gap_side_offset").randrange(len(OPEN_SIDES))
    for index, bbox in enumerate(bboxes):
        r0, c0, rh, rw = bbox
        draw_rect_outline(grid, r0, c0, rh, rw, 1)
        side = OPEN_SIDES[(side_offset + sample_index + index) % len(OPEN_SIDES)]
        gr, gc = _gap_for_bbox(bbox, side, ctx.draw_rng(f"gap_position_{index}"))
        grid[gr][gc] = background
    return grid


def _mode(grid: Iterable[Iterable[int]]) -> int:
    counts = Counter(value for row in grid for value in row)
    if not counts:
        raise ValueError("empty grid")
    return counts.most_common(1)[0][0]


def _components_of_color(grid, color: int) -> list[list[tuple[int, int]]]:
    h, w = len(grid), len(grid[0])
    remaining = {
        (r, c)
        for r, row in enumerate(grid)
        for c, value in enumerate(row)
        if value == color
    }
    result: list[list[tuple[int, int]]] = []
    while remaining:
        first = min(remaining)
        remaining.remove(first)
        stack = [first]
        cells = []
        while stack:
            r, c = stack.pop()
            cells.append((r, c))
            for dr, dc in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                point = (r + dr, c + dc)
                if point in remaining:
                    remaining.remove(point)
                    stack.append(point)
        result.append(sorted(cells))
    return result


def _rectangle_facts(cells: Iterable[tuple[int, int]]) -> tuple[dict | None, str | None]:
    cellset = set(cells)
    if not cellset:
        return None, "empty color-1 component"
    r0 = min(r for r, _ in cellset)
    r1 = max(r for r, _ in cellset)
    c0 = min(c for _, c in cellset)
    c1 = max(c for _, c in cellset)
    rh, rw = r1 - r0 + 1, c1 - c0 + 1
    if rh < 4 or rw < 4:
        return None, f"outline bbox {rh}x{rw} is smaller than 4x4"
    perimeter = {
        (r, c)
        for r in range(r0, r1 + 1)
        for c in range(c0, c1 + 1)
        if r in (r0, r1) or c in (c0, c1)
    }
    extras = sorted(cellset - perimeter)
    if extras:
        return None, "component has color-1 cells inside its rectangle interior"
    missing = sorted(perimeter - cellset)
    if len(missing) != 1:
        return None, f"expected exactly one outline gap, found {len(missing)}"
    gap = missing[0]
    if gap in {(r0, c0), (r0, c1), (r1, c0), (r1, c1)}:
        return None, "gap is on a corner, not inside one open side"
    if gap[0] == r0:
        side = "up"
    elif gap[0] == r1:
        side = "down"
    elif gap[1] == c0:
        side = "left"
    elif gap[1] == c1:
        side = "right"
    else:
        return None, "gap is not on the outline"
    return {
        "bbox": (r0, c0, r1, c1),
        "height": rh,
        "width": rw,
        "gap": gap,
        "side": side,
    }, None


def self_check(grid, *, difficulty=None, meta=None):
    del difficulty, meta
    if not isinstance(grid, (list, tuple)) or not grid:
        return ["expected a nonempty rectangular grid"]
    if not isinstance(grid[0], (list, tuple)) or not grid[0]:
        return ["expected a nonempty rectangular grid"]
    width = len(grid[0])
    if any(not isinstance(row, (list, tuple)) or len(row) != width for row in grid):
        return ["grid rows must be rectangular"]
    if any(type(value) is not int or not 0 <= value <= 9 for row in grid for value in row):
        return ["cells must be integer ARC colors 0..9 (not bool)"]

    background = _mode(grid)
    errors = []
    if background in (1, 2):
        errors.append(
            f"background/mode color {background} conflicts with outline or output color"
        )
    if any(value not in (background, 1) for row in grid for value in row):
        errors.append("input may contain only the background and color-1 outlines")

    components = _components_of_color(grid, 1)
    if not (1 <= len(components) <= 3):
        errors.append(f"expected 1-3 color-1 open rectangles, found {len(components)}")
    for index, cells in enumerate(components):
        _, message = _rectangle_facts(cells)
        if message:
            errors.append(f"component {index}: {message}")
    return errors


def strict_canonical_like(grid):
    errors = list(self_check(grid))
    if not errors:
        profile = f"{len(grid)}x{len(grid[0])}"
        if profile not in SCENE_PROFILES:
            errors.append(
                f"canvas profile {profile} is outside the declared canonical-profile manifold"
            )
    return errors


def observe_overrides(grid):
    errors = self_check(grid)
    if errors:
        raise ValueError("cannot observe axes on an invalid grid: " + "; ".join(errors))
    return {
        "scene_profile": f"{len(grid)}x{len(grid[0])}",
        "background": _mode(grid),
    }


def _apply_intended(
    grid,
    *,
    object_filter: Callable[[dict], bool] | None = None,
):
    """Python review mirror; the canonical Racket program remains authority."""
    background = _mode(grid)
    out = deepcopy(grid)
    h, w = len(grid), len(grid[0])
    for cells in _components_of_color(grid, 1):
        facts, message = _rectangle_facts(cells)
        if message:
            raise ValueError(message)
        assert facts is not None
        if object_filter is not None and not object_filter(facts):
            continue
        r0, c0, r1, c1 = facts["bbox"]
        for r in range(r0 + 1, r1):
            for c in range(c0 + 1, c1):
                if out[r][c] == background:
                    out[r][c] = 2
        gap_r, gap_c = facts["gap"]
        if facts["side"] == "up":
            beam = ((r, gap_c) for r in range(0, r0 + 1))
        elif facts["side"] == "down":
            beam = ((r, gap_c) for r in range(r1, h))
        elif facts["side"] == "left":
            beam = ((gap_r, c) for c in range(0, c0 + 1))
        else:
            beam = ((gap_r, c) for c in range(c1, w))
        for r, c in beam:
            if out[r][c] == background:
                out[r][c] = 2
    return out


def _four_by_four_only(grid):
    """RIVAL: incorrectly ignores every lawful non-4x4 open rectangle."""
    return _apply_intended(
        grid,
        object_filter=lambda facts: (facts["height"], facts["width"]) == (4, 4),
    )


def _has_non_4x4_rectangle(grid) -> bool:
    try:
        return any(
            (facts["height"], facts["width"]) != (4, 4)
            for facts, message in (
                _rectangle_facts(cells) for cells in _components_of_color(grid, 1)
            )
            if facts is not None and message is None
        )
    except (TypeError, ValueError):
        return False


