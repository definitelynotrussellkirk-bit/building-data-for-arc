"""Reconcile retained diagnostic rivals with supported actual Racket results."""
from pathlib import Path
import hashlib, importlib.util, json
from arcpuzzles.catalog import Catalog
from reviewer_support import canonical_pairs
root = Path(__file__).resolve().parents[1]

def read(path): return json.loads((root/path).read_text())
def write(path,data): (root/path).write_text(json.dumps(data,indent=2)+'\n')
def module(path):
    spec=importlib.util.spec_from_file_location('verification_'+str(hash(path)),path)
    result=importlib.util.module_from_spec(spec);spec.loader.exec_module(result);return result

def diff(a,b):
    if len(a)!=len(b) or any(len(x)!=len(y) for x,y in zip(a,b)):
        return {'different_shape':True}
    return {'different_shape':False,'different_cells':sum(x!=y for r,s in zip(a,b) for x,y in zip(r,s))}

case=read('checks/baseline-ambiguity/case.json')
actual=read('checks/baseline-ambiguity/racket.json')
old_path=root/'.review/baseline/repo/generators/627260bf308f/generator.py'
old=module(old_path)
old_hash=hashlib.sha256(old_path.read_bytes()).hexdigest()
assert old_hash==case['source_generator_sha256']
assert all(r['valid_output'] and r['error'] is None for r in actual['results'])
inputs=case['case']['inputs']
assert inputs==read('checks/baseline-ambiguity/inputs.json')
assert inputs==[old.generate(0,i,difficulty='easy') for i in range(7,11)]
assert all(old.self_check(g)==[] for g in inputs)
truth=[r['output'] for r in actual['results']]
assert truth==case['case']['diagnostic_outputs']
agreements=[a==b for a,b in zip(truth,case['case']['rival_outputs'])]
assert agreements==[True,True,True,False],agreements
write('checks/baseline-ambiguity/verified.json',{
    'status':'reproduced', 'task_id':'627260bf308f',
    'input_generation_sha256':old_hash,'applied_current_generator_sha256':actual['generator_sha256'],
    'executed_rule_hash':actual['executed_rule_hash'], 'seed':0,'band':'easy','overrides':{},
    'demo_indices':[7,8,9],'query_index':10,'validator_errors':[[],[],[],[]],
    'rival':'bbox_area', 'rival_matches_racket':agreements,
    'query_difference':diff(truth[3],case['case']['rival_outputs'][3]),
    'independent_diagnostic_matches_racket':[True]*4,
    'note':'Inputs were generated by the retained baseline. apply records the current selected source, not the source of externally supplied inputs. These identities are intentionally distinct.'})
for tid in ('ce3c0854174d','2a43e4f3a796'):
    base=f'checks/audit/{tid}'
    meta=read(base+'/metadata.json');a=read(base+'/racket.json');r=read(base+'/rival.json');g=read(base+'/input.json')
    assert a['generator_sha256']==meta['generator_sha256']
    assert a['executed_rule_hash']==meta['rule_hash'] and a['rule_hash_matches_catalog']
    assert len(a['results'])==1 and a['results'][0]['input']==g
    result=a['results'][0]
    assert result['valid_output'] and result['error'] is None and result['output']!=r
    record={'task_id':tid,'status':'reproduced','generator_sha256':meta['generator_sha256'],
            'executed_rule_hash':a['executed_rule_hash'],'validator_errors':meta['validator_errors'],
            'actual_differs_from_rival':True,'difference':diff(result['output'],r)}
    if tid=='2a43e4f3a796':
        pairs=canonical_pairs(tid,root=root/'repo')
        matching=[pair for pair in pairs if pair['input']==g]
        assert matching and matching[0]['output']==result['output']
        record['actual_matches_canonical']=True
    write(base+'/comparison.json',record)
print('Baseline demo-fit/query-disagreement and both audit counterexamples verified against retained actual Racket outputs.')
