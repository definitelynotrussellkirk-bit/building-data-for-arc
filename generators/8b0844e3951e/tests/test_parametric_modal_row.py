@pytest.mark.parametrize("scope", ["global", "modal_row"])
@pytest.mark.parametrize("seed", [0, 17])
def test_two_demonstrations_alone_reject_declared_shortcuts(seed, scope):
    """No query labels are used to eliminate a plausible competing rule."""
    prototype = _prototype()
    episode = prototype.generate(seed, {"scope": scope}, 2, 4)
    predictions = []
    for pair in episode["train"]:
        rivals = prototype.rival_colors(pair["input"])
        assert REQUIRED_RIVALS <= set(rivals)
        assert all(type(rivals[name]) is int and 0 <= rivals[name] <= 9 for name in REQUIRED_RIVALS)
        predictions.append((rivals, pair["output"][0][0]))
    survivors = {
        name for name in REQUIRED_RIVALS
        if all(rivals[name] == target for rivals, target in predictions)
    }
    assert survivors == {scope}


def test_settings_share_inputs_and_query_count_does_not_change_first_turn():
    prototype = _prototype()
    global_episode = prototype.generate(17, {"scope": "global"}, 3, 4)
    row_episode = prototype.generate(17, {"scope": "modal_row"}, 3, 4)
    short_episode = prototype.generate(17, {"scope": "modal_row"}, 3, 1)
    for split in ("train", "test"):
        assert [p["input"] for p in global_episode[split]] == [p["input"] for p in row_episode[split]]
    assert short_episode["train"] == row_episode["train"]
    assert short_episode["test"] == row_episode["test"][:1]
    assert any(a["output"] != b["output"] for a, b in zip(global_episode["train"], row_episode["train"]))


@pytest.mark.parametrize("scope", ["global", "modal_row"])
def test_fourth_query_uses_substantive_content_across_30_by_30_canvas(scope):
    episode = _prototype().generate(17, {"scope": scope}, 3, 4)
    grid = episode["test"][3]["input"]
    assert len(grid) == 30 and all(len(row) == 30 for row in grid)
    assert sum(v != 0 for row in grid for v in row) >= 180
    for start_r, start_c in ((0, 0), (0, 15), (15, 0), (15, 15)):
        values = [grid[r][c] for r in range(start_r, start_r + 15) for c in range(start_c, start_c + 15)]
        assert sum(v != 0 for v in values) >= 20
        assert len(set(values) - {0}) >= 3


def test_generation_is_deterministic_fresh_and_global_rng_pure():
    prototype = _prototype()
    previous_state = random.getstate()
    try:
        random.seed(13051)
        state = random.getstate()
        first = prototype.generate(17, {"scope": "modal_row"}, 3, 4)
        second = prototype.generate(17, {"scope": "modal_row"}, 3, 4)
        assert random.getstate() == state
        assert first == second
        first["train"][0]["input"][0][0] = 99
        assert second["train"][0]["input"][0][0] != 99
        assert prototype.generate(17, {"scope": "modal_row"}, 3, 4) == second
    finally:
        random.setstate(previous_state)


@pytest.mark.parametrize("kind", [
    "empty", "ragged", "bool", "float", "color_out_of_range",
    "global_tie", "row_tie", "local_tie", "empty_local_pool",
])
def test_analysis_rejects_malformed_or_underidentified_inputs(kind):
    grid = [row[:] for row in CAUSAL_INPUT]
    if kind == "empty":
        grid = []
    elif kind == "ragged":
        grid[0].pop()
    elif kind == "bool":
        grid[0][0] = True
    elif kind == "float":
        grid[0][0] = 7.0
    elif kind == "color_out_of_range":
        grid[0][0] = 10
    elif kind == "global_tie":
        grid = [[1, 1, 2], [2, 3, 4], [5, 0, 0]]
    elif kind == "row_tie":
        grid[3][0], grid[0][4] = grid[0][4], grid[3][0]
    elif kind == "local_tie":
        grid[2] = [7, 7, 4, 3, 2]
    elif kind == "empty_local_pool":
        grid[2] = [7, 7, 7, 7, 7]
    with pytest.raises((TypeError, ValueError)):
        _prototype().analyze(grid)
