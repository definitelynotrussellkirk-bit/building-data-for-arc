def _assert_episode_contract(episode, settings, demos, queries):
    assert len(episode["train"]) == demos
    assert len(episode["test"]) == queries
    assert episode["program_solution"] == _prototype().program(settings)
    inputs = []
    for pair in episode["train"] + episode["test"]:
        grid, output = pair["input"], pair["output"]
        assert type(grid) is list and 3 <= len(grid) <= 30
        width = len(grid[0])
        assert 3 <= width <= 30
        assert all(type(row) is list and len(row) == width for row in grid)
        assert all(type(v) is int and 0 <= v <= 9 for row in grid for v in row)
        assert type(output) is list and len(output) == len(grid)
        assert all(type(row) is list and len(row) == width for row in output)
        assert all(type(v) is int and 1 <= v <= 9 for row in output for v in row)
        assert len({v for row in output for v in row}) == 1

        # Independently check the admitted grammar; do not trust sampler metadata.
        frequencies = Counter(v for row in grid for v in row if v)
        ranked = frequencies.most_common()
        assert len(ranked) >= 3 and ranked[0][1] > ranked[1][1]
        global_color = ranked[0][0]
        row_counts = [row.count(global_color) for row in grid]
        assert row_counts.count(max(row_counts)) == 1
        selected_row = row_counts.index(max(row_counts))
        local_counts = Counter(v for v in grid[selected_row] if v not in (0, global_color))
        assert local_counts
        local_ranked = local_counts.most_common()
        assert len(local_ranked) == 1 or local_ranked[0][1] > local_ranked[1][1]
        expected = global_color if settings["scope"] == "global" else local_ranked[0][0]
        assert output[0][0] == expected
        inputs.append(tuple(tuple(row) for row in grid))
    assert len(set(inputs)) == demos + queries


