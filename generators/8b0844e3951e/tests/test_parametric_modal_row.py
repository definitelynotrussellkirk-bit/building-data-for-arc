@lru_cache(maxsize=None)
def _load_source(path: Path, module_name: str):
    assert path.is_file(), f"Required prototype source is missing: {path}"
    spec = importlib.util.spec_from_file_location(module_name, path)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[module_name] = module
    spec.loader.exec_module(module)
    return module


def _prototype():
    return _load_source(PROTOTYPE_PATH, "_test_modal_row_8b0844e3951e")


def test_input_dependent_row_changes_answer_without_changing_global_counts():
    """A histogram-only, fixed-row or global-runner-up solver must fail here."""
    prototype = _prototype()
    first = [row[:] for row in CAUSAL_INPUT]
    moved = [row[:] for row in CAUSAL_INPUT]
    moved[2][1], moved[0][3] = moved[0][3], moved[2][1]
    assert Counter(v for row in first for v in row) == {
        7: 6, 2: 5, 3: 4, 4: 4, 5: 3, 0: 3,
    }
    assert Counter(v for row in moved for v in row) == Counter(
        v for row in first for v in row
    )
    for grid, expected_row, expected_local in ((first, 2, 4), (moved, 0, 2)):
        facts = prototype.analyze(grid)
        assert facts["global_mode"] == 7
        assert facts["selected_row"] == expected_row
        assert facts["local_mode"] == expected_local
        rivals = prototype.rival_colors(grid)
        assert rivals["global"] == 7
        assert rivals["modal_row"] == expected_local
    assert prototype.rival_colors(first)["global_runner_up"] == 2


def test_zero_is_excluded_at_both_frequency_stages():
    """Counting zero or retaining the global mode in the local pool is wrong."""
    prototype = _prototype()
    assert Counter(v for row in ZERO_DOMINANT_INPUT for v in row) == {
        0: 8, 2: 6, 8: 4, 3: 4, 6: 3,
    }
    facts = prototype.analyze(ZERO_DOMINANT_INPUT)
    assert facts["global_mode"] == 2
    assert facts["selected_row"] == 4
    assert facts["local_mode"] == 6
    rivals = prototype.rival_colors(ZERO_DOMINANT_INPUT)
    assert rivals["overall_mode"] == 0
    assert rivals["local_including_zero"] == 0
    assert rivals["local_including_mode"] == 2
    assert rivals["modal_row"] == 6


