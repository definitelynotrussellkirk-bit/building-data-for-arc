def _normalize(cells):
    min_r = min(r for r, _ in cells)
    min_c = min(c for _, c in cells)
    return tuple(sorted((r - min_r, c - min_c) for r, c in cells))


@lru_cache(maxsize=None)
def _shape_variants(size):
    variants = set()
    for base in _BASE_SHAPES[size]:
        current = tuple(base)
        for reflected in (False, True):
            cells = tuple((r, -c if reflected else c) for r, c in current)
            for _ in range(4):
                variants.add(_normalize(cells))
                cells = tuple((c, -r) for r, c in cells)
    return tuple(sorted(variants))


def _bbox_area(cells):
    rows = [r for r, _ in cells]
    columns = [c for _, c in cells]
    return (max(rows) - min(rows) + 1) * (max(columns) - min(columns) + 1)


def _placed_shape(rng, size, zone_top, zone_left, *, required_bbox_area=None):
    variants = _shape_variants(size)
    if required_bbox_area is not None:
        variants = tuple(
            shape for shape in variants if _bbox_area(shape) == required_bbox_area
        )
        if not variants:
            raise RuntimeError(
                f"no size-{size} shape has bounding-box area {required_bbox_area}"
            )
    shape = rng.choice(variants)
    # Anchor every normalized shape at its zone origin. Random within-zone
    # translations can swap the row-major discovery order of two components
    # in the same row band, breaking the declared positional lesson schedule.
    return tuple(sorted((zone_top + r, zone_left + c) for r, c in shape))


def _default_canvas(sample_index, difficulty):
    if difficulty == "easy":
        return 8, 10
    if difficulty == "hard":
        return 9, 11
    return ((8, 10), (9, 11))[sample_index % 2]


def _default_profile(sample_index):
    return (
        "canonical_245",
        "varied_246",
        "canonical_345",
        "varied_246",
    )[sample_index % LESSON_SCHEDULE_PERIOD]


def _draw_axis(ctx, label, full_values, default_values, overrides):
    options = full_values if label in overrides else default_values
    return ctx.draw_choice(label, options)


def _component_cells(ctx, h, w, profile):
    sizes = PROFILE_SIZES[profile]
    count = len(sizes)
    rng = ctx.draw_rng("component_layout")
    zones = (
        (0, 0),
        (0, w - 3),
        (h - 3, 0),
        (h - 3, w - 3),
    )
    selected = sorted(rng.sample(zones, count))

    largest = max(sizes)
    phase = ctx.sample_index % LESSON_SCHEDULE_PERIOD
    rank_code = (0, 1, -1, 1)[phase]
    largest_rank = count - 1 if rank_code == -1 else min(rank_code, count - 1)
    bbox_counterexample = (
        count == 3
        and 4 in sizes
        and largest in (5, 6)
        and phase in (1, 2)
    )
    if bbox_counterexample:
        remaining = list(sizes)
        remaining.remove(largest)
        remaining.remove(4)
        other = remaining[0]
        if largest_rank == 1:
            ordered_sizes = [4, largest, other]
        else:
            ordered_sizes = [4, other, largest]
    else:
        remaining = list(sizes)
        remaining.remove(largest)
        rng.shuffle(remaining)
        ordered_sizes = list(remaining)
        ordered_sizes.insert(largest_rank, largest)

    components = []
    for (zone_top, zone_left), size in zip(selected, ordered_sizes):
        required_area = 6 if bbox_counterexample and size in (4, largest) else None
        components.append(
            _placed_shape(
                rng,
                size,
                zone_top,
                zone_left,
                required_bbox_area=required_area,
            )
        )
    return components


def _validate_request(difficulty, overrides):
    if difficulty not in (None, "easy", "medium", "hard"):
        raise ValueError(f"unknown difficulty {difficulty!r}")
    unknown = sorted(set(overrides) - set(AXES))
    if unknown:
        raise ValueError(f"unknown override axes: {unknown}")
    if any(value is None for value in overrides.values()):
        raise ValueError("explicit override values may not be None")

    for label, lo, hi in (("grid_h", 8, 12), ("grid_w", 10, 14)):
        if label not in overrides:
            continue
        value = overrides[label]
        if type(value) is not int:
            raise TypeError(f"{label} must be an integer, not {type(value).__name__}")
        if not lo <= value <= hi:
            raise ValueError(f"{label}={value} outside [{lo},{hi}]")

    if "component_profile" in overrides:
        value = overrides["component_profile"]
        if not isinstance(value, str):
            raise TypeError("component_profile must be a string")
        if value not in COMPONENT_PROFILES:
            raise ValueError(f"unknown component_profile {value!r}")


def generate(seed, sample_index, *, difficulty=None, **overrides):
    _validate_request(difficulty, overrides)
    ctx = gen_ctx(
        seed=seed,
        sample_index=sample_index,
        version=VERSION,
        task_id=TASK_ID,
        difficulty=difficulty,
        overrides=overrides,
    )
    default_h, default_w = _default_canvas(sample_index, difficulty)
    h = _draw_axis(ctx, "grid_h", tuple(range(8, 13)), (default_h,), overrides)
    w = _draw_axis(ctx, "grid_w", tuple(range(10, 15)), (default_w,), overrides)
    profile = _draw_axis(
        ctx,
        "component_profile",
        COMPONENT_PROFILES,
        (_default_profile(sample_index),),
        overrides,
    )

    grid = full_grid(h, w, 0)
    for component in _component_cells(ctx, h, w, profile):
        for r, c in component:
            grid[r][c] = 1
    errors = self_check(grid)
    if errors:
        raise RuntimeError(f"generator produced an invalid grid: {errors}")
    return grid


def _components_4(grid, color=1):
    h, w = len(grid), len(grid[0])
    seen = set()
    result = []
    for r in range(h):
        for c in range(w):
            if grid[r][c] != color or (r, c) in seen:
                continue
            stack = [(r, c)]
            seen.add((r, c))
            cells = []
            while stack:
                cr, cc = stack.pop()
                cells.append((cr, cc))
                for dr, dc in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                    nr, nc = cr + dr, cc + dc
                    if (
                        0 <= nr < h
                        and 0 <= nc < w
                        and grid[nr][nc] == color
                        and (nr, nc) not in seen
                    ):
                        seen.add((nr, nc))
                        stack.append((nr, nc))
            result.append(tuple(sorted(cells)))
    return sorted(result, key=min)


def _touches_other_component(components):
    owner = {cell: index for index, cells in enumerate(components) for cell in cells}
    for index, cells in enumerate(components):
        for r, c in cells:
            for dr in (-1, 0, 1):
                for dc in (-1, 0, 1):
                    if dr == dc == 0:
                        continue
                    other = owner.get((r + dr, c + dc))
                    if other is not None and other != index:
                        return True
    return False


def _analysis(grid):
    if not isinstance(grid, (list, tuple)) or not grid:
        return None, ["grid must be a nonempty list or tuple of rows"]
    if not all(isinstance(row, (list, tuple)) for row in grid):
        return None, ["every row must be a list or tuple"]
    widths = {len(row) for row in grid}
    if len(widths) != 1 or 0 in widths:
        return None, ["grid must be rectangular and nonempty"]

    h, w = len(grid), next(iter(widths))
    errors = []
    if not 8 <= h <= 12:
        errors.append(f"height {h} outside declared 8..12 range")
    if not 10 <= w <= 14:
        errors.append(f"width {w} outside declared 10..14 range")
    if any(type(value) is not int for row in grid for value in row):
        errors.append("cells must be integer ARC colors")
        return None, errors
    colors = {value for row in grid for value in row}
    if not colors <= {0, 1}:
        errors.append(f"input colors must be exactly background 0 and blue 1, got {sorted(colors)}")
    if 0 not in colors:
        errors.append("background color 0 is missing")
    if 1 not in colors:
        errors.append("input contains no blue component")

    components = _components_4(grid, 1)
    sizes = tuple(sorted(len(component) for component in components))
    profile = PROFILE_BY_SIZES.get(sizes)
    if not 2 <= len(components) <= 4:
        errors.append(f"expected 2-4 blue components, found {len(components)}")
    if profile is None:
        errors.append(f"unsupported blue component-size profile {sizes}")
    if components:
        largest_size = max(map(len, components))
        if sum(len(component) == largest_size for component in components) != 1:
            errors.append(f"largest blue component is not unique: {sizes}")
    if _touches_other_component(components):
        errors.append("distinct blue components touch diagonally or orthogonally")

    facts = {
        "height": h,
        "width": w,
        "colors": colors,
        "components": components,
        "sizes": sizes,
        "profile": profile,
    }
    return facts, errors


def self_check(grid, *, difficulty=None, meta=None):
    """Validate the declared unique-largest-blue grammar."""
    return list(_analysis(grid)[1])


def strict_canonical_like(grid):
    facts, errors = _analysis(grid)
    if errors:
        return list(errors)
    strict_errors = []
    if (facts["height"], facts["width"]) not in CANONICAL_GRID_PROFILES:
        strict_errors.append(
            f"grid profile {(facts['height'], facts['width'])} is outside canonical support"
        )
    if facts["profile"] not in CANONICAL_COMPONENT_PROFILES:
        strict_errors.append(
            f"component profile {facts['profile']!r} is outside canonical support"
        )
    return strict_errors


def observe_overrides(grid):
    facts, errors = _analysis(grid)
    if errors:
        raise ValueError("cannot observe overrides from invalid grid: " + "; ".join(errors))
    return {
        "grid_h": facts["height"],
        "grid_w": facts["width"],
        "component_profile": facts["profile"],
    }


def _reference_output(grid):
    components = _components_4(grid, 1)
    largest_size = max(map(len, components))
    largest = [component for component in components if len(component) == largest_size]
    if len(largest) != 1:
        raise ValueError("reference requires one uniquely largest blue component")
    out = deepcopy(grid)
    for r, c in largest[0]:
        out[r][c] = 7
    return out


def _recolor_component(grid, component):
    out = deepcopy(grid)
    for r, c in component:
        out[r][c] = 7
    return out


def _ranked_blue(grid):
    return _components_4(grid, 1)


def _first_blue(grid):
    return _recolor_component(grid, _ranked_blue(grid)[0])


def _last_blue(grid):
    return _recolor_component(grid, _ranked_blue(grid)[-1])


def _smallest_blue(grid):
    component = min(_ranked_blue(grid), key=lambda cells: (len(cells), min(cells)))
    return _recolor_component(grid, component)


def _largest_bbox_area(grid):
    component = max(_ranked_blue(grid), key=_bbox_area)
    return _recolor_component(grid, component)


def _fixed_size_five(grid):
    components = [component for component in _ranked_blue(grid) if len(component) == 5]
    if not components:
        return deepcopy(grid)
    return _recolor_component(grid, components[0])


def _largest_not_first(grid):
    components = _ranked_blue(grid)
    return len(components[0]) != max(map(len, components))


def _largest_not_last(grid):
    components = _ranked_blue(grid)
    return len(components[-1]) != max(map(len, components))


def _bbox_area_shortcut_fails(grid):
    return _largest_bbox_area(grid) != _reference_output(grid)


def _contains_size_two(grid):
    return any(len(component) == 2 for component in _ranked_blue(grid))


def _winner_not_size_five(grid):
    return max(map(len, _ranked_blue(grid))) != 5


