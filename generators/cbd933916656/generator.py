"""Generator for arc_puzzle_bank_21_set14_bundle:medium_n04 — recolor by perimeter rank.

Canonical rule: treat each non-zero connected component as an object, rank
components by cardinal perimeter from smallest to largest (ties break by size
then bbox), and recolor the ranked components with palette 2, 4, 8.

This generator emits exactly three separated components with distinct
perimeters, so the canonical rule always exercises all three rank colors and
never runs past the three-color output palette.
"""
from __future__ import annotations

from puzzle_generators.base import gen_ctx
from puzzle_generators.helpers.grid import full_grid

GENERATOR_ID = "cbd933916656"
VERSION = "2.0.0"  # 1.1.0 was a touch-degree generator; canonical task is perimeter-rank.
TASK_ID = "cbd933916656"

SUMMARY = (
    "0-bg grid containing exactly THREE separated same-color components with "
    "strictly distinct cardinal perimeters. Rule: rank components by perimeter "
    "from smallest to largest, then recolor them 2, 4, and 8 respectively."
)

INVARIANTS = [
    "background is 0",
    "exactly 3 separated 4-connected non-bg components",
    "component perimeters are strictly distinct, avoiding rank ties",
    "the canonical 3-color palette is never indexed out of range",
]

PALETTE_KINDS = ("default", "warm", "cool", "varied")
DEGENERATE_TEXTURES = ("perimeter_tie", "too_many_components", "single_component")
HELPFUL_TEXTURES = PALETTE_KINDS

AXES = {
    "grid_h":         {"type": "int", "default": "rng 12..18", "valid": "8..24"},
    "grid_w":         {"type": "int", "default": "rng 16..24", "valid": "10..30"},
    "n_components":   {"type": "int", "default": "3", "valid": "3"},
    "palette_kind":   {"type": "str", "default": "rng helpful",
                       "valid": "|".join(PALETTE_KINDS)},
    "palette_size":   {"type": "int", "default": "1", "valid": "1"},
    "position_bias":  {"type": "str", "default": "separated_components",
                       "valid": "separated_components"},
    "n_distinct_colors": {"type": "int", "default": "1", "valid": "1"},
    "density":        {"type": "str", "default": "sparse", "valid": "sparse"},
    "texture":        {"type": "str", "default": "alias for palette_kind",
                       "valid": "|".join(HELPFUL_TEXTURES + DEGENERATE_TEXTURES)},
}


# Shape library keyed by cardinal perimeter.  Each entry is a connected
# polyomino; variants are generated by rotation/reflection at placement time.
SHAPES_BY_PERIMETER = {
    6: [((0, 0), (0, 1))],
    8: [((0, 0), (0, 1), (1, 0)), ((0, 0), (0, 1), (0, 2))],
    10: [((0, 0), (0, 1), (0, 2), (0, 3)), ((0, 1), (1, 0), (1, 1), (1, 2))],
    12: [((0, 0), (0, 1), (0, 2), (1, 1), (2, 1)), ((0, 0), (1, 0), (2, 0), (2, 1), (2, 2))],
}

PERIMETER_BANDS = {
    "easy": ((6, 8, 10),),
    "medium": ((6, 8, 10), (6, 8, 12), (8, 10, 12)),
    "hard": ((8, 10, 12),),
}


def _normalize(cells):
    min_r = min(r for r, _ in cells)
    min_c = min(c for _, c in cells)
    return tuple(sorted((r - min_r, c - min_c) for r, c in cells))


def _variants(cells):
    variants = set()
    pts = list(cells)
    for flip in (False, True):
        cur = [(r, -c if flip else c) for r, c in pts]
        for _ in range(4):
            variants.add(_normalize(cur))
            cur = [(c, -r) for r, c in cur]
    return sorted(variants)


def _can_place(occ, cells, r0, c0, h, w, *, margin=1):
    for dr, dc in cells:
        r = r0 + dr
        c = c0 + dc
        if r < 0 or c < 0 or r >= h or c >= w:
            return False
        for rr in range(max(0, r - margin), min(h, r + margin + 1)):
            for cc in range(max(0, c - margin), min(w, c + margin + 1)):
                if occ[rr][cc]:
                    return False
    return True


def _place(g, occ, cells, r0, c0, color):
    for dr, dc in cells:
        r = r0 + dr
        c = c0 + dc
        g[r][c] = color
        occ[r][c] = True


def _paint_component(g, occ, cells, color, rng):
    h, w = len(g), len(g[0])
    variants = _variants(cells)
    rng.shuffle(variants)
    for shape in variants:
        sh = max(r for r, _ in shape) + 1
        sw = max(c for _, c in shape) + 1
        for _ in range(160):
            r0 = rng.randint(0, h - sh)
            c0 = rng.randint(0, w - sw)
            if _can_place(occ, shape, r0, c0, h, w, margin=1):
                _place(g, occ, shape, r0, c0, color)
                return True
    return False


def generate(seed, sample_index, *, difficulty=None, **overrides):
    ctx = gen_ctx(seed=seed, sample_index=sample_index,
                  version=VERSION, task_id=TASK_ID,
                  difficulty=difficulty, overrides=overrides)
    if overrides.get("texture") in DEGENERATE_TEXTURES:
        return _draw_from_degenerate(overrides["texture"], None)

    if difficulty == "easy":
        h = ctx.draw_int("grid_h", 10, 13)
        w = ctx.draw_int("grid_w", 13, 16)
    elif difficulty == "hard":
        h = ctx.draw_int("grid_h", 16, 22)
        w = ctx.draw_int("grid_w", 20, 28)
    else:
        h = ctx.draw_int("grid_h", 12, 18)
        w = ctx.draw_int("grid_w", 16, 24)

    rng = ctx.draw_rng("layout")
    color = ctx.draw_color("component_color", exclude={0})
    choices = PERIMETER_BANDS.get(difficulty or "medium", PERIMETER_BANDS["medium"])
    band = list(rng.choice(choices))
    rng.shuffle(band)

    # Retry whole layouts because late placement can fail on smaller grids.
    for _attempt in range(60):
        g = full_grid(h, w, 0)
        occ = [[False] * w for _ in range(h)]
        ok = True
        # Paint larger objects first to make placement robust; perimeter order is
        # recovered by the canonical rule, not by draw order.
        for perimeter in sorted(band, reverse=True):
            shape = rng.choice(SHAPES_BY_PERIMETER[perimeter])
            if not _paint_component(g, occ, shape, color, rng):
                ok = False
                break
        if ok:
            return g
    raise ValueError("could not place 3 distinct-perimeter components")


def _draw_from_degenerate(name, rng):
    h, w = 10, 13
    g = full_grid(h, w, 0)
    occ = [[False] * w for _ in range(h)]
    color = 6
    if name == "perimeter_tie":
        # Two dominoes tie on perimeter, so bbox tie-break rather than rank-by-shape
        # determines their output colors.
        _place(g, occ, ((0, 0), (0, 1)), 1, 1, color)
        _place(g, occ, ((0, 0), (0, 1)), 1, 8, color)
        _place(g, occ, ((0, 0), (0, 1), (1, 0)), 6, 5, color)
        return g
    if name == "too_many_components":
        # Canonical palette has only three colors; a fourth object would index past it.
        _place(g, occ, ((0, 0), (0, 1)), 1, 1, color)
        _place(g, occ, ((0, 0), (0, 1), (1, 0)), 1, 6, color)
        _place(g, occ, ((0, 0), (0, 1), (0, 2), (0, 3)), 6, 1, color)
        _place(g, occ, ((0, 0), (0, 1), (0, 2), (1, 1), (2, 1)), 6, 7, color)
        return g
    if name == "single_component":
        # No ranking comparison to learn.
        _place(g, occ, ((0, 0), (0, 1), (0, 2), (1, 1), (2, 1)), 4, 5, color)
        return g
    return g


def _components_nonzero(grid):
    h = len(grid)
    w = len(grid[0]) if h else 0
    seen = set()
    comps = []
    for r in range(h):
        for c in range(w):
            if grid[r][c] == 0 or (r, c) in seen:
                continue
            color = grid[r][c]
            stack = [(r, c)]
            seen.add((r, c))
            comp = []
            while stack:
                rr, cc = stack.pop()
                comp.append((rr, cc))
                for dr, dc in ((-1, 0), (1, 0), (0, -1), (0, 1)):
                    nr, nc = rr + dr, cc + dc
                    if 0 <= nr < h and 0 <= nc < w and (nr, nc) not in seen and grid[nr][nc] == color:
                        seen.add((nr, nc))
                        stack.append((nr, nc))
            comps.append(comp)
    return comps


def _cardinal_perimeter(comp):
    s = set(comp)
    perim = 0
    for r, c in s:
        for dr, dc in ((-1, 0), (1, 0), (0, -1), (0, 1)):
            if (r + dr, c + dc) not in s:
                perim += 1
    return perim


def self_check(grid, *, difficulty=None, meta=None):
    errs = []
    if not grid or not grid[0] or any(len(row) != len(grid[0]) for row in grid):
        return ["grid must be non-empty and rectangular"]
    if any(v < 0 or v > 9 for row in grid for v in row):
        errs.append("grid values must be digits 0..9")
    comps = _components_nonzero(grid)
    if len(comps) != 3:
        errs.append("expected exactly three separated non-background components")
        return errs
    colors = {grid[comp[0][0]][comp[0][1]] for comp in comps}
    if len(colors) != 1:
        errs.append("normal perimeter-rank samples should use one object color")
    perims = [_cardinal_perimeter(comp) for comp in comps]
    if len(set(perims)) != 3:
        errs.append("component perimeters must be strictly distinct")
    return errs
