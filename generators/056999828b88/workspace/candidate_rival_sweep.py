#!/usr/bin/env python3
"""Search a broad family of canonical-fitting geometric ordering shortcuts.

The probe deliberately excludes exact object cell count.  It builds 8×8
(primary feature, tie-break feature) orderings, verifies that each fits every
canonical pair, then asks whether any ordering survives a sliding four-demo
lesson generated by the selected implementation.
"""
from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
import sys
from collections.abc import Iterable, Sequence
from pathlib import Path
from typing import Any

WORKSPACE = Path(__file__).resolve().parent
TASK_DIR = WORKSPACE.parent
REPO = TASK_DIR.parents[1]
RUNTIME = REPO / "shared" / "runtime"
if str(RUNTIME) not in sys.path:
    sys.path.insert(0, str(RUNTIME))

BANDS = ("easy", "medium", "hard")
PRIMARY_FEATURES = (
    "bbox_area",
    "bbox_semiperimeter",
    "boundary_perimeter",
    "adjacency_edges",
    "boundary_cells",
    "max_span",
    "min_span",
    "legacy_rank",
)
TIEBREAK_FEATURES = (
    "shape_key",
    "bbox_area",
    "bbox_semiperimeter",
    "boundary_perimeter",
    "adjacency_edges",
    "boundary_cells",
    "legacy_rank",
    "span_pair",
)


def _load(path: Path):
    spec = importlib.util.spec_from_file_location(
        f"candidate_sweep_056999828b88_{hashlib.sha256(path.read_bytes()).hexdigest()[:12]}",
        path,
    )
    if spec is None or spec.loader is None:
        raise RuntimeError(f"cannot import generator at {path}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _canonical_pairs(path: Path) -> list[dict[str, Any]]:
    with path.open() as source:
        for line in source:
            row = json.loads(line)
            if row.get("task_id") == "056999828b88":
                return row["train"] + [row["test"]]
    raise ValueError(f"canonical task 056999828b88 missing from {path}")


def _feature_values(module, piece: dict[str, Any]) -> dict[str, Any]:
    max_span = max(piece["h"], piece["w"])
    min_span = min(piece["h"], piece["w"])
    return {
        "bbox_area": piece["h"] * piece["w"],
        "bbox_semiperimeter": piece["h"] + piece["w"],
        "boundary_perimeter": module._boundary_perimeter(piece),
        "adjacency_edges": module._adjacency_edges(piece),
        "boundary_cells": module._boundary_cells(piece),
        "max_span": max_span,
        "min_span": min_span,
        "legacy_rank": module._LEGACY_SHAPE_RANK.get(
            module._shape_key(piece["cells"]), 99
        ),
        "shape_key": module._shape_key(piece["cells"]),
        "span_pair": (max_span, min_span),
    }


def _orders(module, grid: list[list[int]]) -> tuple[tuple[int, ...], dict[str, tuple[int, ...]]]:
    pieces = [module._crop_piece(obj) for obj in module._components(grid)]
    rows = [(piece, _feature_values(module, piece)) for piece in pieces]
    truth = tuple(
        piece["color"]
        for piece in sorted(pieces, key=lambda piece: (piece["size"], piece["color"]))
    )
    candidates = {}
    for primary in PRIMARY_FEATURES:
        for tie in TIEBREAK_FEATURES:
            name = f"{primary}|{tie}"
            candidates[name] = tuple(
                piece["color"]
                for piece, values in sorted(
                    rows,
                    key=lambda row: (
                        row[1][primary],
                        row[1][tie],
                        row[0]["color"],
                    ),
                )
            )
    return truth, candidates


def canonical_fitting_candidates(
    module, canonical_pairs: Sequence[dict[str, Any]]
) -> tuple[str, ...]:
    matching: set[str] | None = None
    for pair in canonical_pairs:
        truth, candidates = _orders(module, pair["input"])
        if module._size_pack(pair["input"]) != pair["output"]:
            raise ValueError("canonical output no longer matches declared size-order rule")
        here = {name for name, order in candidates.items() if order == truth}
        matching = here if matching is None else matching & here
    return tuple(sorted(matching or ()))


def run_sweep(
    module,
    canonical_pairs: Sequence[dict[str, Any]],
    *,
    seeds: Iterable[int],
    samples_per_record: int,
) -> dict[str, Any]:
    if samples_per_record < int(module.EXAMPLES_NEEDED):
        raise ValueError("samples_per_record must cover at least one complete lesson")
    seed_values = tuple(seeds)
    candidates = canonical_fitting_candidates(module, canonical_pairs)
    survivor_counts = {name: 0 for name in candidates}
    survivor_examples = {name: [] for name in candidates}
    errors: list[dict[str, Any]] = []
    lesson_windows = 0

    for seed in seed_values:
        for band in BANDS:
            matches: list[dict[str, bool]] = []
            for sample_index in range(samples_per_record):
                try:
                    grid = module.generate(seed, sample_index, difficulty=band)
                    self_errors = module.self_check(grid, difficulty=band)
                    if self_errors:
                        raise ValueError("; ".join(self_errors))
                    truth, orders = _orders(module, grid)
                    matches.append(
                        {name: orders[name] == truth for name in candidates}
                    )
                except Exception as exc:  # retain bounded diagnostics, do not mask
                    if len(errors) < 20:
                        errors.append(
                            {
                                "seed": seed,
                                "band": band,
                                "sample_index": sample_index,
                                "type": type(exc).__name__,
                                "message": str(exc),
                            }
                        )
                    matches.append({name: False for name in candidates})

            n_demos = int(module.EXAMPLES_NEEDED)
            for start in range(samples_per_record - n_demos + 1):
                lesson_windows += 1
                window = matches[start : start + n_demos]
                for name in candidates:
                    if all(row[name] for row in window):
                        survivor_counts[name] += 1
                        if len(survivor_examples[name]) < 10:
                            survivor_examples[name].append(
                                {
                                    "seed": seed,
                                    "band": band,
                                    "start_sample_index": start,
                                }
                            )

    survivors = [
        {
            "candidate": name,
            "surviving_windows": survivor_counts[name],
            "examples": survivor_examples[name],
        }
        for name in candidates
        if survivor_counts[name]
    ]
    return {
        "schema": "056999828b88-candidate-rival-sweep/2",
        "generator_version": getattr(module, "VERSION", None),
        "primary_features": list(PRIMARY_FEATURES),
        "tiebreak_features": list(TIEBREAK_FEATURES),
        "candidate_feature_tie_pairs": len(PRIMARY_FEATURES)
        * len(TIEBREAK_FEATURES),
        "canonical_fitting_candidates": len(candidates),
        "candidate_names": list(candidates),
        "records": len(seed_values) * len(BANDS),
        "samples_per_record": samples_per_record,
        "lesson_windows": lesson_windows,
        "survivors": survivors,
        "errors": errors,
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--generator",
        type=Path,
        default=TASK_DIR / "generator.py",
    )
    parser.add_argument(
        "--canonical",
        type=Path,
        default=REPO / "shared" / "data" / "canonical" / "puzzles.jsonl",
    )
    parser.add_argument("--seed-start", type=int, default=0)
    parser.add_argument("--seeds", type=int, default=32)
    parser.add_argument("--samples-per-record", type=int, default=12)
    parser.add_argument("--out", type=Path)
    args = parser.parse_args()
    if args.seeds < 1:
        parser.error("--seeds must be positive")
    generator_path = args.generator.resolve()
    module = _load(generator_path)
    report = {
        "generator": str(generator_path),
        "generator_sha256": hashlib.sha256(generator_path.read_bytes()).hexdigest(),
        **run_sweep(
            module,
            _canonical_pairs(args.canonical.resolve()),
            seeds=range(args.seed_start, args.seed_start + args.seeds),
            samples_per_record=args.samples_per_record,
        ),
    }
    rendered = json.dumps(report, indent=2, sort_keys=True) + "\n"
    if args.out:
        args.out.write_text(rendered)
    else:
        sys.stdout.write(rendered)
    return 0 if not report["errors"] and not report["survivors"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
