"""gen1: off-center doubly-mirrored mosaic occluded by an 8-rectangle.

Scene: value(r,c) is drawn per symmetry ORBIT under the group generated by
c -> al - c and r -> au - r (both axes are offset from the grid center;
reflections that land out of bounds leave those cells free), giving a dense
mosaic that is mirror-symmetric about both axes. A solid rectangle of 8s (a
color the mosaic never uses) occludes part of it, placed so every hidden cell
keeps at least one visible in-bounds mirror image. Transform: detect each axis
as the unique largest conflict-free reflection overlap on the visible cells,
then output the rectangle's hidden content.

Every training lesson contains separate witnesses that require horizontal and
vertical recovery.  The two witness demonstrations also use different offsets
for each axis and different output shapes, ruling out one-axis, centered-axis,
fixed-offset, and fixed-shape shortcuts before the query is shown.
"""
from __future__ import annotations

from copy import deepcopy

from puzzle_generators.base import gen_ctx

VERSION = "1.1.0"
TASK_ID = "generic_mosaic_occlusion_gen1"
RULE_HASH = "6e414ea28b65"

HOLE = 8
DIFFICULTY_DIMS = {
    "easy": (18, 22),
    "medium": (22, 27),
    "hard": (26, 30),
}

PROGRAM = """(rule!
 ;; A mosaic mirror-symmetric about an OFF-CENTER vertical and horizontal
 ;; axis is occluded by a solid rectangle of 8s. Find each axis as the
 ;; reflection (c -> al - c / r -> au - r) with the largest conflict-free
 ;; overlap on visible cells, then output the occluded rectangle's hidden
 ;; content, each cell recovered from its first visible mirror image.
 (lambda (g)
   (let ()
     (define h (rows g))
     (define w (cols g))
     (define hole 8)
     (define bb (bbox-of-cells (find-color g hole)))
     (define r1 (first bb))
     (define c1 (second bb))
     (define r2 (nth bb 2))
     (define c2 (nth bb 3))
     (define (axis-score a2 vert)
       (for*/fold ((n 0)) ((r (in-range h)) (c (in-range w)))
         (if (< n 0)
             n
             (let ((rr (if (= vert 1) r (- a2 r)))
                   (cc (if (= vert 1) (- a2 c) c)))
               (if (in-bounds? rr cc h w)
                   (let ((v (at g r c)) (u (at g rr cc)))
                     (cond ((or (= v hole) (= u hole)) n)
                           ((= v u) (+ n 1))
                           (else -1)))
                   n)))))
     (define (best-axis vert maxa)
       (first (reduce (lambda (best a2)
                        (let ((s (axis-score a2 vert)))
                          (if (> s (second best)) (list a2 s) best)))
                      (list 0 0)
                      (range 1 maxa))))
     (define al (best-axis 1 (- (* 2 w) 2)))
     (define au (best-axis 0 (- (* 2 h) 2)))
     (grid-from-fn (+ (- r2 r1) 1) (+ (- c2 c1) 1)
       (lambda (i j)
         (let* ((pr (+ r1 i))
                (pc (+ c1 j))
                (hits (filter (lambda (p)
                                (and (in-bounds? (first p) (second p) h w)
                                     (!= (at g (first p) (second p)) hole)))
                              (list (list pr (- al pc))
                                    (list (- au pr) pc)
                                    (list (- au pr) (- al pc))))))
           (at g (first (first hits)) (second (first hits)))))))))"""


def _valid_grid(grid):
    return bool(
        isinstance(grid, list)
        and grid
        and all(isinstance(row, list) and row for row in grid)
        and len({len(row) for row in grid}) == 1
        and all(
            isinstance(value, int)
            and not isinstance(value, bool)
            and 0 <= value <= 9
            for row in grid
            for value in row
        )
    )


def _axis_score(g, a2, vert):
    """Visible-cell agreement count, or -1 when a reflection conflicts."""
    h, w = len(g), len(g[0])
    score = 0
    for r in range(h):
        for c in range(w):
            rr, cc = (r, a2 - c) if vert else (a2 - r, c)
            if not (0 <= rr < h and 0 <= cc < w):
                continue
            value, reflected = g[r][c], g[rr][cc]
            if value == HOLE or reflected == HOLE:
                continue
            if value != reflected:
                return -1
            score += 1
    return score


def _axis_scores(g, vert):
    h, w = len(g), len(g[0])
    maxa = 2 * (w if vert else h) - 2
    return [(a2, _axis_score(g, a2, vert)) for a2 in range(1, maxa)]


def _detect_axis(g, vert):
    """Python mirror of best-axis: earliest max under strict ``>``."""
    best_a, best_s = 0, 0
    for a2, score in _axis_scores(g, vert):
        if score > best_s:
            best_a, best_s = a2, score
    return best_a


def _unique_best_axis(g, vert):
    """Return the axis only when the positive maximum score is unique."""
    scores = _axis_scores(g, vert)
    best = max(score for _, score in scores)
    winners = [a2 for a2, score in scores if score == best]
    return winners[0] if best > 0 and len(winners) == 1 else None


def _hole_bbox(g):
    cells = [
        (r, c)
        for r, row in enumerate(g)
        for c, value in enumerate(row)
        if value == HOLE
    ]
    if not cells:
        return None
    r1 = min(r for r, _ in cells)
    c1 = min(c for _, c in cells)
    r2 = max(r for r, _ in cells)
    c2 = max(c for _, c in cells)
    return r1, c1, r2, c2


def _mirror_support(g, r, c, al, au):
    """Names of visible mirror images in the oracle's preference order."""
    h, w = len(g), len(g[0])
    support = []
    for name, (rr, cc) in (
        ("horizontal", (r, al - c)),
        ("vertical", (au - r, c)),
        ("double", (au - r, al - c)),
    ):
        if 0 <= rr < h and 0 <= cc < w and g[rr][cc] != HOLE:
            support.append(name)
    return tuple(support)


def _support_counts(g, al, au):
    counts = {
        "horizontal_only": 0,
        "vertical_only": 0,
        "both_direct": 0,
        "double_only": 0,
        "unrecoverable": 0,
    }
    for r, row in enumerate(g):
        for c, value in enumerate(row):
            if value != HOLE:
                continue
            support = set(_mirror_support(g, r, c, al, au))
            horizontal = "horizontal" in support
            vertical = "vertical" in support
            if horizontal and not vertical:
                counts["horizontal_only"] += 1
            elif vertical and not horizontal:
                counts["vertical_only"] += 1
            elif horizontal and vertical:
                counts["both_direct"] += 1
            elif "double" in support:
                counts["double_only"] += 1
            else:
                counts["unrecoverable"] += 1
    return counts


def _apply(g):
    """Python mirror of ``PROGRAM``."""
    h, w = len(g), len(g[0])
    bbox = _hole_bbox(g)
    if bbox is None:
        raise ValueError("input has no occluding 8-rectangle")
    r1, c1, r2, c2 = bbox
    al = _detect_axis(g, vert=True)
    au = _detect_axis(g, vert=False)
    out = []
    for pr in range(r1, r2 + 1):
        row = []
        for pc in range(c1, c2 + 1):
            hit = None
            for rr, cc in (
                (pr, al - pc),
                (au - pr, pc),
                (au - pr, al - pc),
            ):
                if 0 <= rr < h and 0 <= cc < w and g[rr][cc] != HOLE:
                    hit = g[rr][cc]
                    break
            row.append(hit)
        out.append(row)
    return out


def _build_mosaic(rng, h, w, al, au, palette):
    """Random color per symmetry orbit under c -> al-c, r -> au-r."""

    def canon(r, c):
        reflected_r = au - r
        reflected_c = al - c
        canonical_r = min(r, reflected_r) if 0 <= reflected_r < h else r
        canonical_c = min(c, reflected_c) if 0 <= reflected_c < w else c
        return canonical_r, canonical_c

    colors = {}
    g = [[0] * w for _ in range(h)]
    for r in range(h):
        for c in range(w):
            key = canon(r, c)
            if key not in colors:
                colors[key] = rng.choice(palette)
            g[r][c] = colors[key]
    return g


def _dims_for(rng, difficulty):
    low, high = DIFFICULTY_DIMS[difficulty]
    return rng.randint(low, high), rng.randint(low, high)


def _build_pair(
    rng,
    difficulty,
    *,
    axis_offsets=None,
    required_support=None,
    forbidden_output_shapes=(),
):
    """Build one unambiguous pair, optionally forcing a shortcut witness."""
    for _attempt in range(240):
        h, w = _dims_for(rng, difficulty)
        if axis_offsets is None:
            al_offset = rng.randint(1, 3)
            au_offset = rng.randint(1, 3)
        else:
            al_offset, au_offset = axis_offsets
        # Both axes are genuinely off-center; offsets are measured in half-cells.
        al = w - 1 + al_offset
        au = h - 1 + au_offset
        n_colors = rng.randint(6, 9)
        palette = rng.sample([value for value in range(10) if value != HOLE], n_colors)
        full = _build_mosaic(rng, h, w, al, au, palette)
        patch_h = rng.randint(3, min(9, h - 4))
        patch_w = rng.randint(3, min(9, w - 4))
        patch_r = rng.randint(0, h - patch_h)
        patch_c = rng.randint(0, w - patch_w)
        g = deepcopy(full)
        for r in range(patch_r, patch_r + patch_h):
            for c in range(patch_c, patch_c + patch_w):
                g[r][c] = HOLE

        if _unique_best_axis(g, True) != al or _unique_best_axis(g, False) != au:
            continue
        support = _support_counts(g, al, au)
        if support["unrecoverable"] or support["double_only"]:
            continue
        if required_support and support[required_support] == 0:
            continue
        out = _apply(g)
        if any(value is None for row in out for value in row):
            continue
        shape = (len(out), len(out[0]))
        if shape in forbidden_output_shapes:
            continue
        if len({value for row in out for value in row}) < 3:
            continue
        return g, out
    raise ValueError(
        "could not place a recoverable, uniquely oriented occluder "
        f"with support={required_support!r}"
    )


def _lesson_identifiability_errors(demos):
    """Reject lessons compatible with named one-axis/fixed-parameter rivals."""
    errors = []
    horizontal_only_pairs = 0
    vertical_only_pairs = 0
    al_offsets = set()
    au_offsets = set()
    output_shapes = set()
    for pair in demos:
        g = pair.get("input") if isinstance(pair, dict) else None
        out = pair.get("output") if isinstance(pair, dict) else None
        if not _valid_grid(g) or not _valid_grid(out):
            continue
        h, w = len(g), len(g[0])
        al = _detect_axis(g, True)
        au = _detect_axis(g, False)
        al_offsets.add(al - (w - 1))
        au_offsets.add(au - (h - 1))
        output_shapes.add((len(out), len(out[0])))
        support = _support_counts(g, al, au)
        horizontal_only_pairs += int(support["horizontal_only"] > 0)
        vertical_only_pairs += int(support["vertical_only"] > 0)

    if horizontal_only_pairs < 1:
        errors.append("training lesson lacks a horizontal-only recovery witness")
    if vertical_only_pairs < 1:
        errors.append("training lesson lacks a vertical-only recovery witness")
    if len(al_offsets) < 2:
        errors.append("training lesson does not vary the vertical-axis offset")
    if len(au_offsets) < 2:
        errors.append("training lesson does not vary the horizontal-axis offset")
    if len(output_shapes) < 2:
        errors.append("training lesson does not vary the occluded rectangle shape")
    return errors


def lesson_identifiable(demos, query=None):
    """Public lesson-level semantic gate used by focused tests and reviewers."""
    errors = _lesson_identifiability_errors(list(demos or []))
    if query is not None:
        if not isinstance(query, dict) or not _valid_grid(query.get("input")):
            errors.append("query is missing a valid input grid")
    return errors


def _pair_errors(pair, pair_name, difficulty):
    errors = []
    if not isinstance(pair, dict):
        return [f"{pair_name} is not a pair dictionary"]
    g = pair.get("input")
    out = pair.get("output")
    if not _valid_grid(g) or not _valid_grid(out):
        return [f"{pair_name} has an invalid input or output grid"]

    h, w = len(g), len(g[0])
    low, high = DIFFICULTY_DIMS[difficulty]
    if not (low <= h <= high and low <= w <= high):
        errors.append(f"{pair_name} input dimensions fall outside the {difficulty} band")

    bbox = _hole_bbox(g)
    if bbox is None:
        return errors + [f"{pair_name} has no occluding 8-rectangle"]
    r1, c1, r2, c2 = bbox
    hole_cells = sum(value == HOLE for row in g for value in row)
    bbox_area = (r2 - r1 + 1) * (c2 - c1 + 1)
    if hole_cells != bbox_area or any(
        g[r][c] != HOLE
        for r in range(r1, r2 + 1)
        for c in range(c1, c2 + 1)
    ):
        errors.append(f"{pair_name} color 8 cells are not one solid rectangle")
    if not (3 <= r2 - r1 + 1 <= 9 and 3 <= c2 - c1 + 1 <= 9):
        errors.append(f"{pair_name} occluder dimensions must each be 3..9")
    if (len(out), len(out[0])) != (r2 - r1 + 1, c2 - c1 + 1):
        errors.append(f"{pair_name} output shape does not match the occluder bbox")
    if any(value == HOLE for row in out for value in row):
        errors.append(f"{pair_name} output leaks reserved occluder color 8")
    if len({value for row in out for value in row}) < 3:
        errors.append(f"{pair_name} output has fewer than three mosaic colors")

    al = _unique_best_axis(g, True)
    au = _unique_best_axis(g, False)
    if al is None or au is None:
        errors.append(f"{pair_name} does not have unique best reflection axes")
        return errors
    if al - (w - 1) not in (1, 2, 3):
        errors.append(f"{pair_name} vertical axis is not an allowed off-center offset")
    if au - (h - 1) not in (1, 2, 3):
        errors.append(f"{pair_name} horizontal axis is not an allowed off-center offset")

    support = _support_counts(g, al, au)
    if support["unrecoverable"]:
        errors.append(f"{pair_name} has hidden cells with no visible mirror")
    if support["double_only"]:
        errors.append(f"{pair_name} relies on a diagonal-only recovery branch")

    try:
        expected = _apply(g)
    except Exception as exc:  # pragma: no cover - defensive diagnostic
        errors.append(f"{pair_name} Python oracle mirror raised {type(exc).__name__}")
        return errors
    if out != expected:
        errors.append(f"{pair_name} output does not match the mirror-recovery rule")
        return errors

    reconstructed = deepcopy(g)
    for i, r in enumerate(range(r1, r2 + 1)):
        for j, c in enumerate(range(c1, c2 + 1)):
            reconstructed[r][c] = out[i][j]
    palette = {value for row in reconstructed for value in row}
    if HOLE in palette or not (6 <= len(palette) <= 9):
        errors.append(f"{pair_name} reconstructed palette must contain 6..9 non-8 colors")
    for r in range(h):
        for c in range(w):
            for rr, cc in ((r, al - c), (au - r, c)):
                if 0 <= rr < h and 0 <= cc < w:
                    if reconstructed[r][c] != reconstructed[rr][cc]:
                        errors.append(f"{pair_name} reconstruction breaks declared mirror symmetry")
                        return errors
    return errors


def self_check_task(task):
    """Structural, semantic, and lesson-level checks for emitted tasks."""
    if not isinstance(task, dict):
        return ["task is not a dictionary"]
    errors = []
    difficulty = task.get("difficulty")
    if difficulty not in DIFFICULTY_DIMS:
        return ["task difficulty must be easy, medium, or hard"]
    train = list(task.get("train") or [])
    test = list(task.get("test") or [])
    if not (2 <= len(train) <= 4):
        errors.append("task must contain 2..4 training pairs")
    if not (1 <= len(test) <= 2):
        errors.append("task must contain 1..2 test pairs")
    if task.get("program") != PROGRAM:
        errors.append("task program is not the selected mosaic-occlusion oracle")
    if task.get("concept") != "mosaic_occlusion":
        errors.append("task concept must be mosaic_occlusion")
    meta = task.get("meta") or {}
    if meta.get("version") != VERSION or meta.get("difficulty") != difficulty:
        errors.append("task meta version/difficulty is stale or inconsistent")

    signatures = set()
    for split, pairs in (("train", train), ("test", test)):
        for index, pair in enumerate(pairs):
            errors.extend(_pair_errors(pair, f"{split}[{index}]", difficulty))
            if isinstance(pair, dict):
                signature = repr(pair.get("input"))
                if signature in signatures:
                    errors.append(f"{split}[{index}] duplicates an earlier input")
                signatures.add(signature)

    errors.extend(_lesson_identifiability_errors(train))
    return errors


def generate_task(seed, *, difficulty="medium"):
    if difficulty not in DIFFICULTY_DIMS:
        raise ValueError(f"unsupported difficulty: {difficulty!r}")
    ctx = gen_ctx(
        seed=seed,
        sample_index=0,
        version=VERSION,
        task_id=TASK_ID,
        difficulty=difficulty,
    )
    n_train = ctx.draw_int("n_train", 2, 4)
    n_test = ctx.draw_int("n_test", 1, 2)

    # The first two demonstrations jointly refute horizontal-only and
    # vertical-only recovery, while independently varying both axis offsets.
    plan_rng = ctx.draw_rng("lesson_plan")
    al_offsets = plan_rng.sample([1, 2, 3], 2)
    au_offsets = plan_rng.sample([1, 2, 3], 2)
    support_plan = ["horizontal_only", "vertical_only"]
    plan_rng.shuffle(support_plan)

    pairs = []
    for index in range(n_train + n_test):
        rng = ctx.draw_rng(f"pair_{index}")
        kwargs = {}
        if index < 2:
            kwargs["axis_offsets"] = (al_offsets[index], au_offsets[index])
            kwargs["required_support"] = support_plan[index]
            if index == 1:
                kwargs["forbidden_output_shapes"] = {
                    (len(pairs[0]["output"]), len(pairs[0]["output"][0]))
                }
        gin, gout = _build_pair(rng, difficulty, **kwargs)
        pairs.append({"input": gin, "output": gout})

    return {
        "train": pairs[:n_train],
        "test": pairs[n_train:],
        "program": PROGRAM,
        "concept": "mosaic_occlusion",
        "difficulty": difficulty,
        "meta": {
            "version": VERSION,
            "difficulty": difficulty,
            "lesson_plan": "two-axis-exclusive-witnesses",
        },
    }


