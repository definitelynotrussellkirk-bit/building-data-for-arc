def _draw_axis(ctx, label, full_values, default_values, overrides):
    options = full_values if label in overrides else default_values
    return ctx.draw_choice(label, options)


def _component_cells(ctx, h, w, profile):
    sizes = PROFILE_SIZES[profile]
    count = len(sizes)
    rng = ctx.draw_rng("component_layout")
    zones = (
        (0, 0),
        (0, w - 3),
        (h - 3, 0),
        (h - 3, w - 3),
    )
    selected = sorted(rng.sample(zones, count))

    minimum = min(sizes)
    phase = ctx.sample_index % LESSON_SCHEDULE_PERIOD
    rank_code = (0, 1, -1, 1)[phase]
    minimum_rank = count - 1 if rank_code == -1 else min(rank_code, count - 1)
    remaining = list(sizes)
    remaining.remove(minimum)
    rng.shuffle(remaining)
    ordered_sizes = list(remaining)
    ordered_sizes.insert(minimum_rank, minimum)

    return [
        _placed_shape(rng, size, zone_top, zone_left)
        for (zone_top, zone_left), size in zip(selected, ordered_sizes)
    ]


def _marker_cells(ctx, grid, count):
    if count == 0:
        return ()
    h, w = len(grid), len(grid[0])
    rng = ctx.draw_rng("marker_layout")
    candidates = []
    for r in range(h):
        for c in range(w):
            if grid[r][c] != 0:
                continue
            neighborhood = (
                grid[rr][cc]
                for rr in range(max(0, r - 1), min(h, r + 2))
                for cc in range(max(0, c - 1), min(w, c + 2))
                if (rr, cc) != (r, c)
            )
            if all(value == 0 for value in neighborhood):
                candidates.append((r, c))
    rng.shuffle(candidates)
    selected = []
    for cell in candidates:
        if all(max(abs(cell[0] - r), abs(cell[1] - c)) > 1 for r, c in selected):
            selected.append(cell)
            if len(selected) == count:
                return tuple(sorted(selected))
    raise RuntimeError(f"could not place {count} isolated marker cells")


def _validate_request(sample_index, difficulty, overrides):
    if type(sample_index) is not int:
        raise TypeError("sample_index must be an exact integer (not bool)")
    if sample_index < 0:
        raise ValueError("sample_index must be nonnegative")
    if difficulty not in (None, "easy", "medium", "hard"):
        raise ValueError(f"unknown difficulty {difficulty!r}")
    unknown = sorted(set(overrides) - set(AXES))
    if unknown:
        raise ValueError(f"unknown override axes: {unknown}")
    if any(value is None for value in overrides.values()):
        raise ValueError("explicit override values may not be None")

    for label, lo, hi in (
        ("grid_h", 8, 12),
        ("grid_w", 10, 14),
        ("marker_count", 0, 2),
    ):
        if label not in overrides:
            continue
        value = overrides[label]
        if type(value) is not int:
            raise TypeError(f"{label} must be an integer, not {type(value).__name__}")
        if not lo <= value <= hi:
            raise ValueError(f"{label}={value} outside [{lo},{hi}]")

    if "component_profile" in overrides:
        value = overrides["component_profile"]
        if not isinstance(value, str):
            raise TypeError("component_profile must be a string")
        if value not in COMPONENT_PROFILES:
            raise ValueError(f"unknown component_profile {value!r}")


def generate(seed, sample_index, *, difficulty=None, **overrides):
    _validate_request(sample_index, difficulty, overrides)
    ctx = gen_ctx(
        seed=seed,
        sample_index=sample_index,
        version=VERSION,
        task_id=TASK_ID,
        difficulty=difficulty,
        overrides=overrides,
    )
    default_h, default_w = _default_canvas(sample_index, difficulty)
    h = _draw_axis(ctx, "grid_h", tuple(range(8, 13)), (default_h,), overrides)
    w = _draw_axis(ctx, "grid_w", tuple(range(10, 15)), (default_w,), overrides)
    profile = _draw_axis(
        ctx,
        "component_profile",
        COMPONENT_PROFILES,
        (_default_profile(sample_index),),
        overrides,
    )
    marker_count = _draw_axis(
        ctx,
        "marker_count",
        tuple(range(3)),
        (_default_marker_count(sample_index),),
        overrides,
    )

    grid = full_grid(h, w, 0)
    for component in _component_cells(ctx, h, w, profile):
        for r, c in component:
            grid[r][c] = 3
    for r, c in _marker_cells(ctx, grid, marker_count):
        grid[r][c] = 5

    errors = self_check(grid)
    if errors:
        raise RuntimeError(f"generator produced an invalid grid: {errors}")
    return grid


def _components_4(grid, color=3):
    h, w = len(grid), len(grid[0])
    seen = set()
    result = []
    for r in range(h):
        for c in range(w):
            if grid[r][c] != color or (r, c) in seen:
                continue
            stack = [(r, c)]
            seen.add((r, c))
            cells = []
            while stack:
                cr, cc = stack.pop()
                cells.append((cr, cc))
                for dr, dc in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                    nr, nc = cr + dr, cc + dc
                    if (
                        0 <= nr < h
                        and 0 <= nc < w
                        and grid[nr][nc] == color
                        and (nr, nc) not in seen
                    ):
                        seen.add((nr, nc))
                        stack.append((nr, nc))
            result.append(tuple(sorted(cells)))
    return sorted(result, key=min)


def _touches_other_component(components):
    owner = {cell: index for index, cells in enumerate(components) for cell in cells}
    for index, cells in enumerate(components):
        for r, c in cells:
            for dr in (-1, 0, 1):
                for dc in (-1, 0, 1):
                    if dr == dc == 0:
                        continue
                    other = owner.get((r + dr, c + dc))
                    if other is not None and other != index:
                        return True
    return False


def _analysis(grid):
    if not isinstance(grid, (list, tuple)) or not grid:
        return None, ["grid must be a nonempty list or tuple of rows"]
    if not all(isinstance(row, (list, tuple)) for row in grid):
        return None, ["every row must be a list or tuple"]
    widths = {len(row) for row in grid}
    if len(widths) != 1 or 0 in widths:
        return None, ["grid must be rectangular and nonempty"]

    h, w = len(grid), next(iter(widths))
    errors = []
    if not 8 <= h <= 12:
        errors.append(f"height {h} outside declared 8..12 range")
    if not 10 <= w <= 14:
        errors.append(f"width {w} outside declared 10..14 range")
    if any(type(value) is not int for row in grid for value in row):
        errors.append("cells must be integer ARC colors")
        return None, errors
    colors = {value for row in grid for value in row}
    if not colors <= {0, 3, 5}:
        errors.append(
            f"input colors must be background 0, green 3, or marker 5; got {sorted(colors)}"
        )
    if 0 not in colors:
        errors.append("background color 0 is missing")
    if 3 not in colors:
        errors.append("input contains no green component")

    components = _components_4(grid, 3)
    sizes = tuple(sorted(len(component) for component in components))
    profile = PROFILE_BY_SIZES.get(sizes)
    if not 2 <= len(components) <= 4:
        errors.append(f"expected 2-4 green components, found {len(components)}")
    if profile is None:
        errors.append(f"unsupported green component-size profile {sizes}")
    if components:
        minimum = min(map(len, components))
        if sum(len(component) == minimum for component in components) != 1:
            errors.append(f"smallest green component is not unique: {sizes}")
    if _touches_other_component(components):
        errors.append("distinct green components touch diagonally or orthogonally")

    markers = tuple(
        (r, c) for r, row in enumerate(grid) for c, value in enumerate(row) if value == 5
    )
    if not 0 <= len(markers) <= 2:
        errors.append(f"expected 0-2 gray marker cells, found {len(markers)}")
    marker_set = set(markers)
    for r, c in markers:
        for rr in range(max(0, r - 1), min(h, r + 2)):
            for cc in range(max(0, c - 1), min(w, c + 2)):
                if (rr, cc) == (r, c):
                    continue
                if grid[rr][cc] in (3, 5):
                    errors.append(
                        f"gray marker {(r, c)} is not isolated from foreground at {(rr, cc)}"
                    )
                    break
            else:
                continue
            break
    if len(marker_set) != len(markers):
        errors.append("duplicate marker coordinates")

    facts = {
        "height": h,
        "width": w,
        "colors": colors,
        "components": components,
        "sizes": sizes,
        "profile": profile,
        "markers": markers,
    }
    return facts, errors


def self_check(grid, *, difficulty=None, meta=None):
    """Validate the declared unique-smallest-green grammar."""
    return list(_analysis(grid)[1])


def strict_canonical_like(grid):
    facts, errors = _analysis(grid)
    if errors:
        return list(errors)
    strict_errors = []
    if (facts["height"], facts["width"]) not in CANONICAL_GRID_PROFILES:
        strict_errors.append(
            f"grid profile {(facts['height'], facts['width'])} is outside canonical support"
        )
    if facts["profile"] not in CANONICAL_COMPONENT_PROFILES:
        strict_errors.append(
            f"component profile {facts['profile']!r} is outside canonical support"
        )
    if len(facts["markers"]) not in (1, 2):
        strict_errors.append(
            f"marker count {len(facts['markers'])} is outside canonical support"
        )
    return strict_errors


def observe_overrides(grid):
    facts, errors = _analysis(grid)
    if errors:
        raise ValueError("cannot observe overrides from invalid grid: " + "; ".join(errors))
    return {
        "grid_h": facts["height"],
        "grid_w": facts["width"],
        "component_profile": facts["profile"],
        "marker_count": len(facts["markers"]),
    }


def _reference_output(grid):
    components = _components_4(grid, 3)
    minimum = min(map(len, components))
    smallest = [component for component in components if len(component) == minimum]
    if len(smallest) != 1:
        raise ValueError("reference requires one uniquely smallest green component")
    return _recolor_component(grid, smallest[0])


def _recolor_component(grid, component):
    out = deepcopy(grid)
    for r, c in component:
        out[r][c] = 4
    return out


def _ranked_green(grid):
    return _components_4(grid, 3)


def _first_green(grid):
    return _recolor_component(grid, _ranked_green(grid)[0])


def _last_green(grid):
    return _recolor_component(grid, _ranked_green(grid)[-1])


def _largest_green(grid):
    component = max(_ranked_green(grid), key=lambda cells: (len(cells), min(cells)))
    return _recolor_component(grid, component)


def _fixed_size_two(grid):
    components = [component for component in _ranked_green(grid) if len(component) == 2]
    if not components:
        return deepcopy(grid)
    return _recolor_component(grid, components[0])


def _smallest_not_first(grid):
    components = _ranked_green(grid)
    return len(components[0]) != min(map(len, components))


def _smallest_not_last(grid):
    components = _ranked_green(grid)
    return len(components[-1]) != min(map(len, components))


def _smallest_not_largest(grid):
    return _largest_green(grid) != _reference_output(grid)


def _winner_not_size_two(grid):
    return min(map(len, _ranked_green(grid))) != 2


