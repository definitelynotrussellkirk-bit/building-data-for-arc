def _rival_repair_without_color_cycle(grid: Any) -> list[list[int]]:
    analysis = analyze_grid(grid)
    if analysis["errors"] or analysis["facts"] is None:
        raise ValueError("outside the task grammar: " + "; ".join(analysis["errors"]))
    facts = analysis["facts"]
    return _retile_with_map(grid, {color: color for color in facts["row0"]})


def _rival_cycle_visible_only(grid: Any) -> list[list[int]]:
    analysis = analyze_grid(grid)
    if analysis["errors"] or analysis["facts"] is None:
        raise ValueError("outside the task grammar: " + "; ".join(analysis["errors"]))
    facts = analysis["facts"]
    official = rule_mirror(grid)
    out = [row[:] for row in grid]
    for r in range(facts["visible"]):
        for c in range(facts["visible"]):
            out[r][c] = official[r][c]
    return out


def _rival_swap_first_two_only(grid: Any) -> list[list[int]]:
    analysis = analyze_grid(grid)
    if analysis["errors"] or analysis["facts"] is None:
        raise ValueError("outside the task grammar: " + "; ".join(analysis["errors"]))
    order = list(analysis["facts"]["row0"])
    mapping = {color: color for color in order}
    mapping[order[0]], mapping[order[1]] = order[1], order[0]
    return _retile_with_map(grid, mapping)


