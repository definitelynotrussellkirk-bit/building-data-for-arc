def lesson_identifiable(demos, query) -> list[str]:
    """Reject any lesson whose demonstrations leave a named shortcut alive."""
    if len(demos) < EXAMPLES_NEEDED:
        return [f"need at least {EXAMPLES_NEEDED} demonstrations"]

    reasons: list[str] = []
    pairs = [*demos, query]
    for index, pair in enumerate(pairs):
        role = f"demo {index}" if index < len(demos) else "query"
        if not isinstance(pair, dict):
            reasons.append(f"{role} is not an input/output mapping")
            continue
        grid = pair.get("input")
        output = pair.get("output")
        findings = strict_canonical_like(grid)
        if findings:
            reasons.append(f"{role} is outside the task manifold: {findings[:2]}")
            continue
        try:
            expected = rule_mirror(grid)
        except Exception as exc:  # counted and surfaced, never swallowed
            reasons.append(f"{role} mirror raised {type(exc).__name__}: {exc}")
            continue
        if expected != output:
            reasons.append(f"{role} output disagrees with the task rule")
    if reasons:
        return reasons

    for name, competitor in LESSON_COMPETITORS.items():
        try:
            survives = all(
                competitor(demo["input"]) == demo["output"] for demo in demos
            )
            changes_query = competitor(query["input"]) != query["output"]
        except Exception as exc:
            reasons.append(
                f"competitor {name!r} raised {type(exc).__name__}: {exc}"
            )
            continue
        if survives and changes_query:
            reasons.append(
                f"demos do not falsify shortcut {name!r}, which changes the query"
            )
        elif survives:
            reasons.append(
                f"shortcut {name!r} matches every demo and the query; lesson is ambiguous"
            )
    return reasons
