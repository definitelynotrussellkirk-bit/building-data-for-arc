def schedule_profile(seed, sample_index, difficulty=None):
    """Name the deterministic structural profile used by an ordinary draw.

    Difficulty rotates the same complete four-profile curriculum rather than
    shrinking its legal domain.  This keeps every band canonical while making
    the band knob observable for identical (seed, sample_index) calls.
    """
    del seed
    offset = {"easy": 0, "medium": 1, "hard": 2}.get(difficulty, 0)
    return _PROFILE_ORDER[(int(sample_index) + offset) % len(_PROFILE_ORDER)]


def _zigzag(values: list[int]) -> tuple[int, ...]:
    """Low, high, next-low, next-high ...; never numeric order for k >= 3."""
    out: list[int] = []
    lo, hi = 0, len(values) - 1
    while lo <= hi:
        out.append(values[lo])
        lo += 1
        if lo <= hi:
            out.append(values[hi])
            hi -= 1
    return tuple(out)


def _ordered_tile_colors(colors: tuple[int, ...] | list[int], order: str) -> tuple[int, ...]:
    values = sorted(int(value) for value in colors)
    if order == "zigzag":
        return _zigzag(values)
    if order == "reverse":
        return tuple(reversed(values))
    raise ValueError(f"unknown palette order {order!r}")


def _classify_palette_order(row: tuple[int, ...]) -> str:
    values = tuple(sorted(row))
    for name in _PALETTE_ORDERS:
        if row == _ordered_tile_colors(values, name):
            return name
    return "other"


def _grid_shape_errors(grid: Any) -> tuple[list[str], int, int]:
    if not isinstance(grid, list) or not grid:
        return ["grid must be a non-empty list of rows"], 0, 0
    if not isinstance(grid[0], list) or not grid[0]:
        return ["grid rows must be non-empty lists"], 0, 0
    width = len(grid[0])
    if any(not isinstance(row, list) or len(row) != width for row in grid):
        return ["grid must be rectangular"], len(grid), width
    return [], len(grid), width


def analyze_grid(grid: Any) -> dict[str, Any]:
    """Recover task-relevant facts and return every structural violation.

    This is intentionally stricter than merely counting colors.  It verifies
    the exact L-shaped mask, the complete visible periodic signal, the
    canonical profile, and the second-row phase.
    """
    errors, height, width = _grid_shape_errors(grid)
    if errors:
        return {"errors": errors, "facts": None}

    if height != width:
        errors.append(f"expected a square grid, got {height}x{width}")
    if any(
        not isinstance(value, int)
        or isinstance(value, bool)
        or not 1 <= value <= 9
        for row in grid
        for value in row
    ):
        errors.append("all cells must be integer non-zero ARC colors 1..9")
    if errors:
        return {"errors": errors, "facts": None}

    # A tile row never has equal horizontal neighbors.  The removed color is
    # therefore the unique color with a horizontal same-color adjacency.
    adjacency_colors = sorted(
        {
            grid[r][c]
            for r in range(height)
            for c in range(width - 1)
            if grid[r][c] == grid[r][c + 1]
        }
    )
    if len(adjacency_colors) != 1:
        errors.append(
            "expected exactly one removed color with a horizontal same-color run, "
            f"found {adjacency_colors}"
        )
        return {"errors": errors, "facts": None}
    removed = adjacency_colors[0]

    # The unmasked signal is one top-left square.  The first all-removed row
    # and column must agree and every cell must match that exact partition.
    first_removed_row = next(
        (r for r in range(height) if all(value == removed for value in grid[r])),
        height,
    )
    first_removed_col = next(
        (
            c
            for c in range(width)
            if all(grid[r][c] == removed for r in range(height))
        ),
        width,
    )
    if first_removed_row != first_removed_col:
        errors.append(
            "removed complement does not leave a square prefix: "
            f"row boundary {first_removed_row}, column boundary {first_removed_col}"
        )
    visible = min(first_removed_row, first_removed_col)
    if not 2 <= visible < height:
        errors.append(
            f"visible square side must be in 2..{height - 1}, got {visible}"
        )

    if not errors:
        wrong_partition = 0
        for r in range(height):
            for c in range(width):
                should_be_removed = r >= visible or c >= visible
                if (grid[r][c] == removed) != should_be_removed:
                    wrong_partition += 1
        if wrong_partition:
            errors.append(
                f"{wrong_partition} cell(s) violate the exact bottom/right L-shaped mask"
            )
    if errors:
        return {"errors": errors, "facts": None}

    tile_colors = sorted(
        {grid[r][c] for r in range(visible) for c in range(visible)}
    )
    if removed in tile_colors:
        errors.append("removed color appears inside the visible square")
    tile_width = len(tile_colors)
    if not 2 <= tile_width <= 4:
        errors.append(f"expected 2-4 tile colors, found {tile_width}")
    if visible < max(2, tile_width):
        errors.append("visible prefix is too small to identify the 2-row tile")
    if errors:
        return {"errors": errors, "facts": None}

    row0 = tuple(grid[0][c] for c in range(tile_width))
    row1 = tuple(grid[1][c] for c in range(tile_width))
    if len(set(row0)) != tile_width or set(row0) != set(tile_colors):
        errors.append("the first tile row must contain every tile color exactly once")

    shifts = [
        shift
        for shift in range(1, tile_width)
        if row1 == tuple(row0[(c + shift) % tile_width] for c in range(tile_width))
    ]
    if len(shifts) != 1:
        errors.append(
            "the second tile row must be one unique non-zero cyclic shift of the first"
        )
        row_shift = None
    else:
        row_shift = shifts[0]

    if not errors:
        mismatches = 0
        for r in range(visible):
            expected_row = row0 if r % 2 == 0 else row1
            for c in range(visible):
                if grid[r][c] != expected_row[c % tile_width]:
                    mismatches += 1
        if mismatches:
            errors.append(
                f"visible square has {mismatches} cell(s) outside the recovered 2x{tile_width} period"
            )
    if errors:
        return {"errors": errors, "facts": None}

    profile_matches = [
        name
        for name, spec in _PROFILE_SPECS.items()
        if (
            spec["size"] == height
            and spec["visible"] == visible
            and spec["tile_width"] == tile_width
            and spec["row_shift"] == row_shift
        )
    ]
    if len(profile_matches) != 1:
        errors.append(
            "grid does not match one canonical structural profile: "
            f"size={height}, visible={visible}, tile_width={tile_width}, "
            f"row_shift={row_shift}"
        )
        return {"errors": errors, "facts": None}

    profile = profile_matches[0]
    facts = {
        "height": height,
        "width": width,
        "visible": visible,
        "removed": removed,
        "tile_width": tile_width,
        "tile_colors": tuple(tile_colors),
        "row0": row0,
        "row1": row1,
        "row_shift": row_shift,
        "profile": profile,
        "palette_order": _classify_palette_order(row0),
    }
    return {"errors": [], "facts": facts}


def observe_overrides(grid: Any) -> dict[str, str]:
    """Recover both declared exact axes from the returned grid."""
    analysis = analyze_grid(grid)
    if analysis["errors"] or analysis["facts"] is None:
        raise ValueError("cannot observe malformed grid: " + "; ".join(analysis["errors"]))
    facts = analysis["facts"]
    return {
        "profile": facts["profile"],
        "palette_order": facts["palette_order"],
    }


def self_check(grid: Any, *, difficulty=None, meta=None) -> list[str]:
    """Validate the complete generated/canonical teaching grammar."""
    del difficulty
    analysis = analyze_grid(grid)
    errors = list(analysis["errors"])
    if errors or analysis["facts"] is None:
        return errors

    requested = {}
    if isinstance(meta, dict):
        candidate = meta.get("overrides", meta)
        if isinstance(candidate, dict):
            requested = {name: candidate[name] for name in AXES if name in candidate}
    if requested:
        observed = observe_overrides(grid)
        for name, value in requested.items():
            if observed.get(name) != value:
                errors.append(
                    f"{name} requested {value!r}, observed {observed.get(name)!r}"
                )
    return errors


def strict_canonical_like(grid: Any) -> list[str]:
    """Every lawful draw is on one of the exact canonical task profiles."""
    return self_check(grid)


def generate(seed, sample_index, *, difficulty=None, **overrides):
    unknown = sorted(set(overrides) - set(AXES))
    if unknown:
        raise ValueError(f"unknown override axis/axes: {', '.join(unknown)}")

    ctx = gen_ctx(
        seed=seed,
        sample_index=sample_index,
        version=VERSION,
        task_id=TASK_ID,
        difficulty=difficulty,
        overrides=overrides,
    )

    if "profile" in overrides:
        profile = ctx.draw_choice("profile", _PROFILE_ORDER)
    else:
        # Still record the scheduled value as a keyed draw so default-axis
        # provenance and the returned-grid observer can be compared exactly.
        profile = ctx.draw_choice(
            "profile", (schedule_profile(seed, sample_index, difficulty),)
        )
    palette_order = ctx.draw_choice("palette_order", _PALETTE_ORDERS)

    spec = _PROFILE_SPECS[profile]
    size = spec["size"]
    visible = spec["visible"]
    tile_width = spec["tile_width"]
    row_shift = spec["row_shift"]

    palette = ctx.draw_distinct_colors(
        "palette", n=tile_width + 1, exclude={0}
    )
    removed = palette[-1]
    row0 = _ordered_tile_colors(palette[:-1], palette_order)
    row1 = tuple(
        row0[(c + row_shift) % tile_width] for c in range(tile_width)
    )

    grid = full_grid(size, size, removed)
    for r in range(visible):
        tile_row = row0 if r % 2 == 0 else row1
        for c in range(visible):
            grid[r][c] = tile_row[c % tile_width]

    errors = self_check(
        grid,
        difficulty=difficulty,
        meta={"overrides": overrides},
    )
    if errors:
        raise AssertionError("generator constructed an invalid grid: " + "; ".join(errors))
    return grid


def rule_mirror(grid: Any) -> list[list[int]]:
    """Independent Python audit mirror; canonical Racket remains authoritative."""
    analysis = analyze_grid(grid)
    if analysis["errors"] or analysis["facts"] is None:
        raise ValueError("outside the task grammar: " + "; ".join(analysis["errors"]))
    facts = analysis["facts"]
    order = list(facts["row0"])
    color_map = {
        color: order[(index + 1) % len(order)]
        for index, color in enumerate(order)
    }
    return [
        [
            color_map[
                (facts["row0"] if r % 2 == 0 else facts["row1"])[
                    c % facts["tile_width"]
                ]
            ]
            for c in range(facts["width"])
        ]
        for r in range(facts["height"])
    ]


