def _lawful_facts(grid: Any) -> dict[str, Any] | None:
    analysis = analyze_grid(grid)
    return None if analysis["errors"] else analysis["facts"]


def _fact_witness(predicate: Callable[[dict[str, Any]], bool], grid: Any) -> bool:
    facts = _lawful_facts(grid)
    return False if facts is None else bool(predicate(facts))


