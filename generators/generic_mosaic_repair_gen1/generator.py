"""gen1: diag + off-center double-mirror mosaic, black holes, full repair.

Scene: a square n x n mosaic drawn per symmetry ORBIT under the group
generated by transpose and the reflections c -> a - c, r -> a - r (one
shared axis parameter a >= n-1, so the group closes; reflections landing
out of bounds leave cells free). 3-7 black rectangles and a few single
black cells pock it. Transform: detect the axes (largest conflict-free
overlap; diagonal gated on conflict-freedom) and fill every hole from its
first visible image; output the whole repaired grid. Scenes resample
until the repair reproduces the clean mosaic exactly.
"""
from __future__ import annotations

from puzzle_generators.base import gen_ctx

VERSION = "1.0.0"
TASK_ID = "generic_mosaic_repair_gen1"

HOLE = 0

PROGRAM = """(rule!
 ;; A mosaic symmetric about the main DIAGONAL and about OFF-CENTER
 ;; vertical/horizontal mirror axes is pocked with black (0) holes.
 ;; Detect each axis as the largest conflict-free reflection overlap on
 ;; visible cells (diagonal gated on conflict-freedom), then repair the
 ;; WHOLE grid: every hole takes its first visible image under transpose,
 ;; the two mirrors, and their compositions.
 (lambda (g)
   (let ()
     (define h (rows g))
     (define w (cols g))
     (define hole 0)
     (define (axis-score a2 vert)
       (for*/fold ((n 0)) ((r (in-range h)) (c (in-range w)))
         (if (< n 0)
             n
             (let ((rr (if (= vert 1) r (- a2 r)))
                   (cc (if (= vert 1) (- a2 c) c)))
               (if (in-bounds? rr cc h w)
                   (let ((v (at g r c)) (u (at g rr cc)))
                     (cond ((or (= v hole) (= u hole)) n)
                           ((= v u) (+ n 1))
                           (else -1)))
                   n)))))
     (define (best-axis vert maxa)
       (first (reduce (lambda (best a2)
                        (let ((s (axis-score a2 vert)))
                          (if (> s (second best)) (list a2 s) best)))
                      (list 0 0)
                      (range 1 maxa))))
     (define al (best-axis 1 (- (* 2 w) 2)))
     (define au (best-axis 0 (- (* 2 h) 2)))
     (define diag-ok
       (and (= h w)
            (for*/fold ((ok #t)) ((r (in-range h)) (c (in-range w)))
              (and ok
                   (let ((v (at g r c)) (u (at g c r)))
                     (or (= v hole) (= u hole) (= v u)))))))
     (define (fill r c)
       (let* ((cands (append
                      (if diag-ok (list (list c r)) (list))
                      (list (list r (- al c))
                            (list (- au r) c)
                            (list (- au r) (- al c)))
                      (if diag-ok
                          (list (list (- al c) r)
                                (list c (- au r))
                                (list (- al c) (- au r)))
                          (list))))
              (hits (filter (lambda (p)
                              (and (in-bounds? (first p) (second p) h w)
                                   (!= (at g (first p) (second p)) hole)))
                            cands)))
         (if (null? hits)
             hole
             (at g (first (first hits)) (second (first hits))))))
     (grid-from-fn h w
                   (lambda (r c)
                     (if (!= (at g r c) hole) (at g r c) (fill r c)))))))"""


def _detect_axis(g, vert):
    h, w = len(g), len(g[0])
    maxa = 2 * (w if vert else h) - 2
    best_a, best_s = 0, 0
    for a2 in range(1, maxa):
        n = 0
        ok = True
        for r in range(h):
            for c in range(w):
                rr, cc = (r, a2 - c) if vert else (a2 - r, c)
                if 0 <= rr < h and 0 <= cc < w:
                    v, u = g[r][c], g[rr][cc]
                    if v == HOLE or u == HOLE:
                        continue
                    if v != u:
                        ok = False
                        break
                    n += 1
            if not ok:
                break
        if ok and n > best_s:
            best_a, best_s = a2, n
    return best_a


def _apply(g):
    """Python mirror of PROGRAM."""
    h, w = len(g), len(g[0])
    al = _detect_axis(g, True)
    au = _detect_axis(g, False)
    diag_ok = h == w and all(
        g[r][c] == HOLE or g[c][r] == HOLE or g[r][c] == g[c][r]
        for r in range(h) for c in range(w))
    out = []
    for r in range(h):
        row = []
        for c in range(w):
            if g[r][c] != HOLE:
                row.append(g[r][c])
                continue
            cands = ([(c, r)] if diag_ok else []) + \
                [(r, al - c), (au - r, c), (au - r, al - c)] + \
                ([(al - c, r), (c, au - r), (al - c, au - r)]
                 if diag_ok else [])
            v = HOLE
            for rr, cc in cands:
                if 0 <= rr < h and 0 <= cc < w and g[rr][cc] != HOLE:
                    v = g[rr][cc]
                    break
            row.append(v)
        out.append(row)
    return out


def _build_mosaic(rng, n, a, palette):
    """Random color per orbit under transpose + reflections with axis a."""
    colors = {}

    def orbit(r, c):
        seen = set()
        stack = [(r, c)]
        while stack:
            p = stack.pop()
            if p in seen:
                continue
            seen.add(p)
            pr, pc = p
            for q in ((pc, pr), (pr, a - pc), (a - pr, pc)):
                if 0 <= q[0] < n and 0 <= q[1] < n and q not in seen:
                    stack.append(q)
        return min(seen)

    g = [[0] * n for _ in range(n)]
    for r in range(n):
        for c in range(n):
            k = orbit(r, c)
            if k not in colors:
                colors[k] = rng.choice(palette)
            g[r][c] = colors[k]
    return g


def _dims_for(rng, difficulty):
    if difficulty == "easy":
        return rng.randint(16, 20)
    if difficulty == "hard":
        return rng.randint(26, 30)
    return rng.randint(20, 26)


def _build_pair(rng, difficulty):
    for _attempt in range(60):
        n = _dims_for(rng, difficulty)
        a = n - 1 + rng.randint(0, 3)
        n_colors = rng.randint(5, 8)
        palette = rng.sample(range(1, 10), n_colors)
        clean = _build_mosaic(rng, n, a, palette)
        g = [row[:] for row in clean]
        n_holes = {"easy": 3, "medium": 5, "hard": 7}[difficulty]
        for _hn in range(n_holes):
            hh = rng.randint(1, 4)
            hw = rng.randint(1, 4)
            r0 = rng.randint(0, n - hh)
            c0 = rng.randint(0, n - hw)
            for r in range(r0, r0 + hh):
                for c in range(c0, c0 + hw):
                    g[r][c] = HOLE
        if all(v != HOLE for row in g for v in row):
            continue
        if _apply(g) != clean:
            continue  # unrecoverable hole or mis-detected axis — resample
        return g, clean
    raise ValueError("could not build a recoverable scene")


def generate_task(seed, *, difficulty="medium"):
    ctx = gen_ctx(seed=seed, sample_index=0, version=VERSION,
                  task_id=TASK_ID, difficulty=difficulty)
    n_train = ctx.draw_int("n_train", 2, 4)
    n_test = ctx.draw_int("n_test", 1, 2)
    pairs = []
    for idx in range(n_train + n_test):
        rng = ctx.draw_rng(f"pair_{idx}")
        gin, gout = _build_pair(rng, difficulty)
        pairs.append({"input": gin, "output": gout})
    return {
        "train": pairs[:n_train],
        "test": pairs[n_train:],
        "program": PROGRAM,
        "concept": "mosaic_repair",
        "difficulty": difficulty,
    }


