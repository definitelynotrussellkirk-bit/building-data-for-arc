from __future__ import annotations
import hashlib, importlib.util, json
from pathlib import Path

PACKET = Path(__file__).resolve().parents[2]
REPO = PACKET / 'repo'
AUDIT = Path(__file__).resolve().parent


def load_gen(task):
    path=REPO/'generators'/task/'generator.py'
    spec=importlib.util.spec_from_file_location('audit_'+task,path)
    mod=importlib.util.module_from_spec(spec); assert spec and spec.loader
    spec.loader.exec_module(mod)
    return mod,path


def comps(grid):
    h,w=len(grid),len(grid[0]); seen=set(); out=[]
    for sr in range(h):
      for sc in range(w):
        if grid[sr][sc]==0 or (sr,sc) in seen: continue
        stack=[(sr,sc)]; comp=[]
        while stack:
          r,c=stack.pop()
          if (r,c) in seen or grid[r][c]==0: continue
          seen.add((r,c)); comp.append((r,c))
          for dr,dc in ((-1,0),(1,0),(0,-1),(0,1)):
            nr,nc=r+dr,c+dc
            if 0<=nr<h and 0<=nc<w: stack.append((nr,nc))
        out.append(comp)
    return out


def crop(grid,comp):
    rs=[r for r,c in comp]; cs=[c for r,c in comp]
    r1,r2,c1,c2=min(rs),max(rs),min(cs),max(cs)
    return [row[c1:c2+1] for row in grid[r1:r2+1]]


def pack_height_color_desc(grid):
    items=[]
    for comp in comps(grid):
        cr=crop(grid,comp)
        color=min(grid[r][c] for r,c in comp if grid[r][c]!=0)
        items.append((len(cr),color,cr))
    items.sort(key=lambda x:(-x[0],-x[1]))
    h=sum(len(x[2]) for x in items)+max(0,len(items)-1)
    w=max(len(row) for _,_,cr in items for row in cr)
    out=[[0]*w for _ in range(h)]
    top=0
    for _,_,cr in items:
        for r,row in enumerate(cr):
            for c,v in enumerate(row):
                if v: out[top+r][c]=v
        top+=len(cr)+1
    return out


def zero_count_shortcut(grid):
    classes=[]
    for si in range(3):
        start=si*5
        zeros={(r,c) for r in range(4) for c in range(4) if grid[r][start+c]==0}
        center={(r,c) for r in (1,2) for c in (1,2)}
        bottom={(r,c) for r in (2,3) for c in (1,2)}
        full_edges={(r,c) for r in range(4) for c in (0,3)}
        if not zeros: cls=2
        elif zeros==center: cls=8
        elif zeros==bottom: cls=4
        elif zeros==full_edges: cls=3
        else: cls=2
        classes.append(cls)
    return [[cls]*3 for cls in classes]


def build(task,rival_name,rival_fn,provenance,domain_note):
    d=AUDIT/task
    apply=json.loads((d/'racket.json').read_text())
    grid=json.loads((d/'input.json').read_text())
    actual=apply['results'][0]['output']
    rival=rival_fn(grid)
    gen,path=load_gen(task)
    validation=gen.self_check(grid)
    (d/'rival.json').write_text(json.dumps(rival,indent=2)+'\n')
    record={
      'schema':'arcpuzzles-audit-counterexample-v1',
      'task_id':task,
      'generator_sha256':apply['generator_sha256'],
      'local_generator_sha256':hashlib.sha256(path.read_bytes()).hexdigest(),
      'executed_rule_hash':apply['executed_rule_hash'],
      'rule_text_sha256':apply['rule_text_sha256'],
      'input_provenance':provenance,
      'input_passes_self_check':validation==[],
      'self_check_reasons':validation,
      'domain_note':domain_note,
      'input_grid':grid,
      'actual_racket_output':actual,
      'actual_output_sha256':apply['results'][0]['output_sha256'],
      'rival_name':rival_name,
      'rival_output':rival,
      'rival_differs':rival!=actual,
      'apply_command':apply['command'],
      'apply_cwd':apply['cwd'],
      'evidence_files':{
        'input':f'checks/audit/{task}/input.json',
        'racket':f'checks/audit/{task}/racket.json',
        'rival':f'checks/audit/{task}/rival.json',
        'distribution_probe':f'checks/audit/{task}/distribution_probe.json',
      }
    }
    (d/'counterexample.json').write_text(json.dumps(record,indent=2,sort_keys=True)+'\n')
    return record

