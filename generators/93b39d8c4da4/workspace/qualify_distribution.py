#!/usr/bin/env python3
"""Source-bound semantic/distribution qualification for generator 93b39d8c4da4.

The probe intentionally discovers the live generator declarations instead of
copying rival or witness names.  It verifies claimed canonical shortcuts against
all usable canonical pairs, then assembles complete four-demo lessons at every
cyclic schedule start.  Outputs are generated by the independent Python mirror;
Racket parity remains the responsibility of the inherited rule-smoke and the
small retained counterexamples.
"""
from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
from collections import Counter, defaultdict
from pathlib import Path
from types import ModuleType
from typing import Any

TASK_ID = "93b39d8c4da4"
HERE = Path(__file__).resolve()
TASK_ROOT = HERE.parents[1]
REPO_ROOT = HERE.parents[3]
CANONICAL_PATH = REPO_ROOT / "shared/data/canonical/puzzles.jsonl"
BANDS = ("easy", "medium", "hard")


def _load_generator(path: Path | None = None) -> ModuleType:
    source = path or (TASK_ROOT / "generator.py")
    spec = importlib.util.spec_from_file_location(
        f"qualification_generator_{TASK_ID}", source
    )
    if spec is None or spec.loader is None:
        raise RuntimeError(f"cannot import generator from {source}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _grid_hash(grid: list[list[int]]) -> str:
    raw = json.dumps(grid, separators=(",", ":"), sort_keys=False).encode()
    return hashlib.sha256(raw).hexdigest()


def _canonical_row() -> dict[str, Any]:
    with CANONICAL_PATH.open(encoding="utf-8") as handle:
        for line in handle:
            row = json.loads(line)
            if row.get("task_id") == TASK_ID:
                return row
    raise RuntimeError(f"canonical task {TASK_ID} missing")


def _canonical_pairs() -> list[dict[str, Any]]:
    row = _canonical_row()
    test = row["test"]
    return list(row["train"]) + (list(test) if isinstance(test, list) else [test])


def _counter_to_json(counter: Counter) -> dict[str, int]:
    return {str(key): counter[key] for key in sorted(counter, key=str)}


def qualify(
    *,
    generator: ModuleType | None = None,
    lessons_per_band: int = 100,
    seed_base: int = 930000,
) -> dict[str, Any]:
    """Return a JSON-serializable qualification report.

    Each lesson receives its own seed.  Its schedule start is
    ``lesson_index % len(SCHEDULE_PROFILES)`` and it contains four consecutive
    demonstrations plus one query.  Therefore 100 lessons per band produce 500
    generated pairs, while all four cyclic starts occur 25 times per band.
    """
    if lessons_per_band < 1:
        raise ValueError("lessons_per_band must be positive")
    gen = generator or _load_generator()
    generator_path = Path(gen.__file__).resolve()
    competitors = dict(gen.LESSON_COMPETITORS)
    shortcuts = dict(gen.CANONICAL_SHORTCUTS)
    witnesses = dict(gen.SEMANTIC_WITNESSES)
    schedule = tuple(gen.SCHEDULE_PROFILES)
    examples_needed = int(gen.EXAMPLES_NEEDED)

    failures: list[dict[str, Any]] = []
    canonical_results: dict[str, Any] = {}
    canonical_pairs = _canonical_pairs()
    for name, rival in shortcuts.items():
        mismatches = []
        for pair_index, pair in enumerate(canonical_pairs):
            try:
                rival_output = rival(pair["input"])
            except Exception as exc:  # retained as evidence, never hidden
                mismatches.append(
                    {"pair_index": pair_index, "error": f"{type(exc).__name__}: {exc}"}
                )
                continue
            if rival_output != pair["output"]:
                mismatches.append({"pair_index": pair_index, "output_mismatch": True})
        canonical_results[name] = {
            "pairs_checked": len(canonical_pairs),
            "fits_all": not mismatches,
            "mismatches": mismatches,
        }
        if mismatches:
            failures.append(
                {
                    "kind": "claimed_canonical_shortcut_does_not_fit",
                    "shortcut": name,
                    "mismatches": mismatches,
                }
            )

    band_reports: dict[str, Any] = {}
    band_offsets = {band: index * 1_000_000 for index, band in enumerate(BANDS)}
    for band in BANDS:
        unique_inputs: set[str] = set()
        profile_counts: Counter = Counter()
        start_counts: Counter = Counter()
        dimension_counts: Counter = Counter()
        template_counts: Counter = Counter()
        mark_counts: Counter = Counter()
        layout_counts: Counter = Counter()
        witness_hits: Counter = Counter()
        rival_disagreements: Counter = Counter()
        lessons_identifiable = 0
        generated_pairs = 0
        selfcheck_failures = 0
        lesson_failures: list[dict[str, Any]] = []

        for lesson_index in range(lessons_per_band):
            start = lesson_index % len(schedule)
            seed = seed_base + band_offsets[band] + lesson_index
            start_counts[start] += 1
            pairs: list[dict[str, Any]] = []
            for offset in range(examples_needed + 1):
                sample_index = start + offset
                profile = gen.schedule_profile(seed, sample_index, band)
                profile_counts[profile] += 1
                grid = gen.generate(seed, sample_index, difficulty=band)
                issues = gen.self_check(grid, difficulty=band)
                if issues:
                    selfcheck_failures += 1
                    failures.append(
                        {
                            "kind": "generated_selfcheck_failure",
                            "band": band,
                            "lesson_index": lesson_index,
                            "sample_index": sample_index,
                            "issues": issues,
                        }
                    )
                observed = gen.observe_overrides(grid)
                dimension_counts[(observed["grid_h"], observed["grid_w"])] += 1
                template_counts[observed["template_id"]] += 1
                mark_counts[observed["n_marks"]] += 1
                layout_counts[observed["layout_mode"]] += 1
                unique_inputs.add(_grid_hash(grid))
                output = gen.rule_mirror(grid)
                pair = {"input": grid, "output": output}
                pairs.append(pair)
                generated_pairs += 1
                for name, witness in witnesses.items():
                    if witness(grid):
                        witness_hits[name] += 1
                for name, rival in competitors.items():
                    if rival(grid) != output:
                        rival_disagreements[name] += 1

            demos, query = pairs[:examples_needed], pairs[examples_needed]
            findings = gen.lesson_identifiable(demos, query)
            surviving = [
                name
                for name, rival in competitors.items()
                if all(rival(pair["input"]) == pair["output"] for pair in demos)
            ]
            if not findings and not surviving:
                lessons_identifiable += 1
            else:
                item = {
                    "lesson_index": lesson_index,
                    "seed": seed,
                    "start": start,
                    "findings": findings,
                    "surviving_competitors": surviving,
                }
                lesson_failures.append(item)
                failures.append({"kind": "lesson_not_identifiable", "band": band, **item})

        for name in witnesses:
            if witness_hits[name] == 0:
                failures.append(
                    {"kind": "declared_witness_never_emitted", "band": band, "witness": name}
                )
        band_reports[band] = {
            "lessons_total": lessons_per_band,
            "lessons_identifiable": lessons_identifiable,
            "lesson_failures": lesson_failures,
            "generated_pairs": generated_pairs,
            "unique_inputs": len(unique_inputs),
            "selfcheck_failures": selfcheck_failures,
            "cyclic_start_counts": _counter_to_json(start_counts),
            "profile_counts": _counter_to_json(profile_counts),
            "dimension_counts": _counter_to_json(dimension_counts),
            "template_id_counts": _counter_to_json(template_counts),
            "mark_count_counts": _counter_to_json(mark_counts),
            "layout_mode_counts": _counter_to_json(layout_counts),
            "witness_hits": _counter_to_json(witness_hits),
            "rival_disagreements": _counter_to_json(rival_disagreements),
        }

    return {
        "schema": "arc-generator-qualification-v1",
        "task_id": TASK_ID,
        "generator_path": str(generator_path),
        "generator_sha256": _sha(generator_path),
        "sampler": {
            "bands": list(BANDS),
            "lessons_per_band": lessons_per_band,
            "seed_base": seed_base,
            "lesson_seed": "seed_base + band_index*1000000 + lesson_index",
            "schedule_start": "lesson_index modulo len(SCHEDULE_PROFILES)",
            "lesson_assembly": (
                f"{examples_needed} consecutive demonstrations plus one consecutive query; "
                "independent seed per lesson"
            ),
            "output_oracle": "generator.rule_mirror (Racket checked separately)",
        },
        "contract": {
            "examples_needed": examples_needed,
            "schedule_profiles": list(schedule),
            "lesson_competitors": sorted(competitors),
            "canonical_shortcuts": sorted(shortcuts),
            "semantic_witnesses": sorted(witnesses),
        },
        "canonical_shortcut_checks": canonical_results,
        "bands": band_reports,
        "failures": failures,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--lessons-per-band", type=int, default=100)
    parser.add_argument("--seed-base", type=int, default=930000)
    parser.add_argument("--generator", type=Path)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()

    generator = _load_generator(args.generator) if args.generator else None
    report = qualify(
        generator=generator,
        lessons_per_band=args.lessons_per_band,
        seed_base=args.seed_base,
    )
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(report, indent=2, sort_keys=True) + "\n")
    print(
        json.dumps(
            {
                "task_id": TASK_ID,
                "generator_sha256": report["generator_sha256"],
                "failures": len(report["failures"]),
                "bands": {
                    band: {
                        "identifiable": data["lessons_identifiable"],
                        "total": data["lessons_total"],
                        "unique_inputs": data["unique_inputs"],
                    }
                    for band, data in report["bands"].items()
                },
                "out": str(args.out),
            },
            sort_keys=True,
        )
    )
    return 0 if not report["failures"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
