#!/usr/bin/env python3
from __future__ import annotations
import hashlib, importlib.util, json
from collections import defaultdict
from pathlib import Path

TASK_ID='9ce2dcf587b8'
EXPECTED_SHA='38d9f9faace1dda2375f755099b8108ae286551d969ca4cce438667df34bb0a8'
EXPECTED_RULE_HASH='e635bf3ddbe0'
HERE=Path(__file__).resolve().parent
REPO=HERE.parents[2]/'repo'
GENERATOR=REPO/'generators'/TASK_ID/'generator.py'
DIAGONALS=((-1,-1),(-1,1),(1,-1),(1,1))


def shoot(grid, markers=None):
    h,w=len(grid),len(grid[0]); source=[list(r) for r in grid]; out=[list(r) for r in grid]
    all_markers=[(r,c,v) for r,row in enumerate(source) for c,v in enumerate(row) if v]
    active=all_markers if markers is None else markers
    for r,c,color in active:
        for dr,dc in DIAGONALS:
            d=1
            while 0<=r+dr*d<h and 0<=c+dc*d<w:
                nr,nc=r+dr*d,c+dc*d
                if source[nr][nc]==0 and out[nr][nc]==0: out[nr][nc]=color
                d+=1
    return out


def color_count_shortcut(grid):
    markers=[(r,c,v) for r,row in enumerate(grid) for c,v in enumerate(row) if v]
    color=markers[0][2]
    expected_count=1+(color-1)%3
    return shoot(grid, markers=markers[:expected_count])


def load_gen():
    spec=importlib.util.spec_from_file_location('audit9ce',GENERATOR)
    assert spec and spec.loader
    mod=importlib.util.module_from_spec(spec); spec.loader.exec_module(mod)
    return mod


def main():
    sha=hashlib.sha256(GENERATOR.read_bytes()).hexdigest(); assert sha==EXPECTED_SHA
    gen=load_gen(); assert gen.RULE_HASH==EXPECTED_RULE_HASH
    mapping=defaultdict(set); default_total=0; default_rival_matches=0; by_band={}
    for band in (None,'easy','medium','hard'):
        label='default' if band is None else band
        band_map=defaultdict(set); matches=0
        for i in range(90):
            grid=gen.generate(810000+i,i,difficulty=band)
            obs=gen.observe_overrides(grid)
            mapping[obs['fgc']].add(obs['n_dots']); band_map[obs['fgc']].add(obs['n_dots'])
            default_total+=1
            if color_count_shortcut(grid)==shoot(grid):
                default_rival_matches+=1; matches+=1
        by_band[label]={'draws':90,'color_to_counts':{str(k):sorted(v) for k,v in sorted(band_map.items())},'rival_matches':matches}
    legal_crosses=[]
    for color in range(1,10):
        for count in range(1,4):
            grid=gen.generate(4200+color*10+count,0,grid_h=7,grid_w=7,fgc=color,n_dots=count)
            legal_crosses.append({'fgc':color,'n_dots':count,'accepted':gen.self_check(grid)==[],'observed':gen.observe_overrides(grid)})
    audit_input=json.loads((HERE/'input.json').read_text())
    racket=json.loads((HERE/'racket.json').read_text())
    racket_output=racket['results'][0]['output']
    correct=shoot(audit_input); rival=color_count_shortcut(audit_input)
    report={
        'schema':'arcpuzzles-adversarial-audit-v1',
        'task_id':TASK_ID,
        'generator_sha256':sha,
        'rule_hash':gen.RULE_HASH,
        'finding':'default schedule perfectly couples marker color to marker count, enabling a color-conditioned multiplicity shortcut',
        'default_census':{
            'seed_formula':'810000 + sample_index',
            'sample_index_range':'0..89 per band',
            'bands':['default','easy','medium','hard'],
            'draw_count':default_total,
            'color_to_counts':{str(k):sorted(v) for k,v in sorted(mapping.items())},
            'rival_match_count':default_rival_matches,
            'by_band':by_band,
        },
        'declared_domain_cross_product':{
            'tested_combinations':len(legal_crosses),
            'accepted_combinations':sum(x['accepted'] and x['observed']['fgc']==x['fgc'] and x['observed']['n_dots']==x['n_dots'] for x in legal_crosses),
            'cases':legal_crosses,
        },
        'counterexample':{
            'generation':{'seed':4242,'sample_index':0,'difficulty':None,'overrides':{'grid_h':7,'grid_w':7,'fgc':1,'n_dots':3}},
            'passes_self_check':gen.self_check(audit_input)==[],
            'observed_overrides':gen.observe_overrides(audit_input),
            'racket_output':racket_output,
            'independent_correct_output':correct,
            'color_count_rival_output':rival,
            'racket_matches_independent':racket_output==correct,
            'rival_differs':racket_output!=rival,
            'input_file':'checks/audit/9ce2dcf587b8/input.json',
            'racket_file':'checks/audit/9ce2dcf587b8/racket.json',
        },
        'domain_statement':'The counterexample is generated by valid exact overrides and passes self_check; the crossed color/count combination is legal but absent from default scheduling.',
        'command':['python3','checks/audit/9ce2dcf587b8/audit_probe.py'],
        'cwd':'WORK',
    }
    assert default_total==default_rival_matches==360
    assert all(v=={1+(k-1)%3} for k,v in mapping.items())
    assert report['declared_domain_cross_product']['accepted_combinations']==27
    assert report['counterexample']['racket_matches_independent'] and report['counterexample']['rival_differs']
    (HERE/'probe.json').write_text(json.dumps(report,indent=2,sort_keys=True)+'\n')
    (HERE/'rival_output.json').write_text(json.dumps(rival,indent=2)+'\n')
    print(json.dumps({'task_id':TASK_ID,'draws':default_total,'rival_matches':default_rival_matches,'legal_crosses':27,'rival_differs':True}))

if __name__=='__main__': main()
