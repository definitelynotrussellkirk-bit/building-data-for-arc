"""Temporary orchestration for a compact, verified packaging snapshot."""
from pathlib import Path
import argparse
import fcntl
import gzip
import hashlib
import json
import shutil
import sys
import tarfile
import tempfile

parser = argparse.ArgumentParser()
parser.add_argument('--packet', type=Path, required=True)
parser.add_argument('--out', type=Path, required=True)
args = parser.parse_args()
root = args.packet.resolve()
work, checks = root / 'WORK', root / 'WORK/checks'
held = Path(tempfile.mkdtemp(prefix='arc-review-packaging-'))
relocated, inventory = [], []
lock_stream = None


def digest(raw):
    return hashlib.sha256(raw).hexdigest()


def hold(file, reason):
    raw = file.read_bytes()
    relative = file.relative_to(work)
    target = held / relative
    target.parent.mkdir(parents=True, exist_ok=True)
    shutil.move(str(file), str(target))
    relocated.append((file, target))
    inventory.append({'path': str(relative), 'bytes': len(raw), 'sha256': digest(raw), 'reason': reason})


try:
    baseline = json.loads((work / 'ASSIGNMENT.json').read_text())['baseline_sha256']
    lock = work / 'repo/REVIEW/.lock'
    if lock.exists():
        assert lock.read_bytes() == b''
        lock_stream = lock.open('rb')
        fcntl.flock(lock_stream, fcntl.LOCK_EX | fcntl.LOCK_NB)
        hold(lock, 'Inactive empty lock created by supported authority-sync; not baseline source.')
    recovery = work / 'repo/var/review/authority-sync'
    if recovery.exists():
        for file in recovery.rglob('*'):
            if not file.is_file():
                continue
            if file.name == 'receipt.json':
                assert file.read_bytes() == (checks / 'authority-sync/apply-receipt.json').read_bytes()
            else:
                suffix = str(file).split('/originals/', 1)[1]
                assert digest(file.read_bytes()) == baseline['repo/' + suffix]
            hold(file, 'Verified authority-sync recovery artifact, already represented by original packet and retained apply receipt.')
    for manifest in checks.rglob('*.compression.json'):
        data = json.loads(manifest.read_text())
        if data.get('schema') != 'arcpuzzles-evidence-gzip-v1':
            continue
        for item in data['files']:
            original = manifest.parent / item['path']
            compressed = (manifest.parent / item['compressed_path']).read_bytes()
            raw = gzip.decompress(compressed)
            assert len(raw) == item['raw_size'] and digest(raw) == item['raw_sha256']
            assert len(compressed) == item['compressed_size'] and digest(compressed) == item['compressed_sha256']
            if original.exists():
                assert original.read_bytes() == raw
                hold(original, 'Exact bytes retained in verified native gzip and neighboring restoration manifest.')
    with tarfile.open(checks / 'parametric/intermediate_eeaa1111.tar.gz', 'r:gz') as archive:
        saved = {m.name: archive.extractfile(m).read() for m in archive.getmembers() if m.isfile()}
    for name in ('final', 'intermediate_source_unpacked'):
        folder = checks / 'parametric' / name
        if folder.exists():
            for file in folder.rglob('*'):
                if file.is_file():
                    assert any(raw == file.read_bytes() for path, raw in saved.items()
                               if path.endswith('/' + str(file.relative_to(folder))))
                    hold(file, 'Duplicate successful intermediate parameter evidence preserved in verified archive and manifest.')
    for file in list(checks.rglob('*')):
        if file.is_file() and (file.suffix in {'.pyc', '.pyo'} or '__pycache__' in file.parts):
            hold(file, 'Generated Python bytecode, not source or evidence.')
    log = checks / 'packaging'
    log.mkdir(exist_ok=True)
    (log / 'snapshot-policy.json').write_text(json.dumps({'schema': 'review-packaging-snapshot-v1',
        'policy': 'Temporarily exclude only verified duplicate evidence, inactive generated lock, checked recovery artifacts, and generated bytecode. Restore every source workspace file after packing.',
        'files': inventory}, indent=2) + '\n')
    (checks / 'review-ledger.json').write_bytes((work / 'RESULTS.json').read_bytes())
    # Use the exact public backend of package_return.py in this process so the
    # verified snapshot is the one observed by the packager.
    sys.path.insert(0, str(work / 'repo/src'))
    from arcpuzzles.review_full_return import build_full_return
    result = build_full_return(work, args.out, bundle_evidence=True)
    (log / (args.out.stem + '.json')).write_text(json.dumps({'cwd': 'packet_root',
        'argv': sys.argv, 'exit_code': 0, 'backend': 'arcpuzzles.review_full_return.build_full_return',
        'result': result}, indent=2) + '\n')
    print(result['zip'])
finally:
    for source, temporary in reversed(relocated):
        source.parent.mkdir(parents=True, exist_ok=True)
        shutil.move(str(temporary), str(source))
    if lock_stream is not None:
        lock_stream.close()
